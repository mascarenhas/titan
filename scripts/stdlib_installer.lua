local cli_stage, cli_root = ...
local script_path = arg and arg[0] or ""
local source_root =
    script_path:match("^(.*)/scripts/stdlib_installer%.lua$")
if script_path == "scripts/stdlib_installer.lua" then source_root = "." end
local direct = source_root ~= nil
if direct then
    if select("#", ...) ~= 2 or type(cli_stage) ~= "string" or
            type(cli_root) ~= "string" then
        io.stderr:write(
            "usage: lua scripts/stdlib_installer.lua STAGE ROOT\n")
        os.exit(2)
    end
    package.path = source_root .. "/?.lua;" ..
        source_root .. "/?/init.lua;" .. package.path
    package.cpath = cli_stage .. "/?.so;" ..
        cli_root .. "/lib/titan/0.16/?.so;" ..
        cli_root .. "/lib/lua/5.5/?.so;" .. package.cpath
end

local lfs = require "lfs"
local types = require "titan-compiler.types"

local installer = {}

local MODULES = {
    "coroutine", "uv", "async", "timer", "fs", "net", "os",
}
local BANNER = "-- Generated by titanc; do not edit.\n"

local function join(root, suffix)
    if root == "/" then return "/" .. suffix end
    return root:gsub("/+$", "") .. "/" .. suffix
end

local function ensure_directory(path)
    local mode = lfs.symlinkattributes(path, "mode")
    if mode == "directory" then return true end
    if mode then return nil, "path '" .. path .. "' is not a directory" end
    local parent = path:match("^(.*)/[^/]+$")
    if parent and parent ~= "" then
        local ok, err = ensure_directory(parent)
        if not ok then return nil, err end
    end
    local ok, err = lfs.mkdir(path)
    if ok or lfs.symlinkattributes(path, "mode") == "directory" then
        return true
    end
    return nil, err
end

local function ensure_parent(path)
    local parent = path:match("^(.*)/[^/]+$")
    if not parent or parent == "" then return true end
    return ensure_directory(parent)
end

local function remove_path(path)
    local mode = lfs.symlinkattributes(path, "mode")
    if mode == "directory" then
        for name in lfs.dir(path) do
            if name ~= "." and name ~= ".." then
                local ok, err = remove_path(path .. "/" .. name)
                if not ok then return nil, err end
            end
        end
        return lfs.rmdir(path)
    elseif mode then
        return os.remove(path)
    end
    return true
end

local function copy_file(source, destination)
    local input, input_err = io.open(source, "rb")
    if not input then return nil, input_err end
    local output, output_err = io.open(destination, "wb")
    if not output then input:close(); return nil, output_err end
    while true do
        local block = input:read(1024 * 1024)
        if not block then break end
        local ok, err = output:write(block)
        if not ok then
            input:close()
            output:close()
            return nil, err
        end
    end
    local input_ok, input_close_err = input:close()
    local output_ok, output_close_err = output:close()
    if not input_ok then return nil, input_close_err end
    if not output_ok then return nil, output_close_err end
    return true
end

local function copy_tree(source, destination)
    local mode = lfs.symlinkattributes(source, "mode")
    if mode == "file" then return copy_file(source, destination) end
    if mode ~= "directory" then
        return nil, "staged path '" .. source .. "' has unsupported type " ..
            tostring(mode)
    end
    local ok, err = ensure_directory(destination)
    if not ok then return nil, err end
    for name in lfs.dir(source) do
        if name ~= "." and name ~= ".." then
            ok, err = copy_tree(source .. "/" .. name,
                destination .. "/" .. name)
            if not ok then return nil, err end
        end
    end
    return true
end

local function read_file(path)
    local file, err = io.open(path, "rb")
    if not file then return nil, err end
    local contents = file:read("*a")
    file:close()
    return contents
end

local function shell_quote(word)
    return "'" .. word:gsub("'", "'\\''") .. "'"
end

local function make_executable(path)
    local ok, why, code = os.execute("chmod 0755 " .. shell_quote(path))
    if ok then return true end
    return nil, "chmod failed for '" .. path .. "' (" .. tostring(why) ..
        (code and (", " .. tostring(code)) or "") .. ")"
end

local function unique_sibling(path, kind)
    local seed = os.tmpname()
    os.remove(seed)
    seed = seed:match("([^/]+)$") or seed:gsub("[^%w]", "_")
    return path .. ".titan-install-" .. kind .. "." .. seed
end

local function platform_name(explicit)
    if explicit and explicit ~= "" then return explicit end
    local pipe = io.popen("uname", "r")
    if not pipe then return "unknown" end
    local value = pipe:read("*a") or ""
    pipe:close()
    return value:match("^%s*(.-)%s*$")
end

local function one_string_result(fn, label)
    local results = table.pack(pcall(fn))
    if not results[1] then
        return nil, label .. " failed: " .. tostring(results[2])
    end
    if results.n ~= 2 or type(results[2]) ~= "string" then
        return nil, label .. " must return exactly one string"
    end
    return results[2]
end

local function validate_image(dso)
    local support_ok, support = pcall(require, "titan")
    if not support_ok or type(support) ~= "table" or
       type(support._loadlib) ~= "function" then
        return nil, "cannot inspect staged titan.so through Titan support: " ..
            tostring(support)
    end
    local loadlib = support._loadlib

    local support_open, support_err = loadlib(dso, "luaopen_titan")
    if not support_open then
        return nil, "staged titan.so is missing luaopen_titan: " ..
            tostring(support_err)
    end
    local support_values = table.pack(pcall(support_open))
    if not support_values[1] or support_values.n ~= 2 or
       type(support_values[2]) ~= "table" or
       type(support_values[2]._loadlib) ~= "function" or
       type(support_values[2]._loadlibglobal) ~= "function" then
        return nil, "staged luaopen_titan does not return the required " ..
            "native support table"
    end

    for _, module in ipairs(MODULES) do
        local modname = "titan." .. module
        local prefix = "titan_" .. module
        local abi, abi_err = loadlib(dso, prefix .. "_abi")
        if not abi then
            return nil, "staged titan.so is missing " .. prefix ..
                "_abi: " .. tostring(abi_err)
        end
        local abi_value, abi_call_err = one_string_result(
            abi, "staged " .. prefix .. "_abi")
        if not abi_value then return nil, abi_call_err end
        if abi_value ~= "0.16" then
            return nil, "staged " .. prefix .. "_abi returned " ..
                tostring(abi_value) .. " instead of 0.16"
        end

        local typefn, type_err = loadlib(dso, prefix .. "_types")
        if not typefn then
            return nil, "staged titan.so is missing " .. prefix ..
                "_types: " .. tostring(type_err)
        end
        local serialized, serialized_err = one_string_result(
            typefn, "staged " .. prefix .. "_types")
        if not serialized then return nil, serialized_err end
        local chunk, parse_err = load(
            "return " .. serialized, "=" .. prefix .. "_types", "t", types)
        if not chunk then return nil, parse_err end
        local decoded = table.pack(pcall(chunk))
        if not decoded[1] then return nil, tostring(decoded[2]) end
        if decoded.n ~= 2 or type(decoded[2]) ~= "table" or
           decoded[2]._tag ~= "Type.Module" or decoded[2].name ~= modname then
            return nil, "staged " .. prefix ..
                "_types does not describe logical module " .. modname
        end
        local serializable, schema_err = pcall(types.serialize, decoded[2])
        if not serializable then
            return nil, "staged " .. prefix ..
                "_types has an invalid interface schema: " ..
                tostring(schema_err)
        end

        for _, symbol in ipairs({
            prefix .. "_init",
            "luaopen_" .. prefix,
        }) do
            local entry, entry_err = loadlib(dso, symbol)
            if not entry then
                return nil, "staged titan.so is missing " .. symbol ..
                    ": " .. tostring(entry_err)
            end
        end
    end
    return true
end

local function validate_stage(stage, is_darwin, image_validator)
    local dso = join(stage, "titan.so")
    if lfs.symlinkattributes(dso, "mode") ~= "file" then
        return nil, "staged standard library has no regular titan.so"
    end
    if is_darwin and
       lfs.symlinkattributes(dso .. ".dSYM", "mode") ~= "directory" then
        return nil, "staged macOS standard library has no titan.so.dSYM"
    end
    local image_ok, image_err = image_validator(dso)
    if not image_ok then return nil, image_err end
    for _, module in ipairs(MODULES) do
        local path = join(stage, "titan/" .. module .. ".lua")
        local contents, err = read_file(path)
        if not contents then return nil, err end
        if contents:sub(1, #BANNER) ~= BANNER then
            return nil, "staged shim '" .. path ..
                "' is not owned by titanc"
        end
        if not contents:find('package.searchpath("titan", package.cpath)',
            1, true) then
            return nil, "staged shim '" .. path ..
                "' does not select provider titan"
        end
        if not contents:find('"luaopen_titan_' .. module .. '"', 1, true) then
            return nil, "staged shim '" .. path ..
                "' does not select its logical Lua entry"
        end
    end
    return true
end

local function add_entry(entries, seen, public, source, mode, label)
    if seen[public] then return end
    seen[public] = true
    entries[#entries + 1] = {
        public = public,
        source = source,
        mode = mode,
        label = label,
    }
end

local function failpoint(position, label)
    local requested = os.getenv("TITAN_INSTALL_FAIL_AT")
    if requested == position .. ":" .. label then
        error("injected standard-library publication failure at " ..
            requested, 0)
    end
end

function installer.publish(options)
    options = options or {}
    local stage = assert(options.stage, "missing staged standard-library root")
    local root = assert(options.root, "missing Titan rocks tree")
    if stage:sub(1, 1) ~= "/" or root:sub(1, 1) ~= "/" then
        return nil, "staging and rocks-tree paths must be absolute"
    end
    stage = stage:gsub("/+$", "")
    root = root:gsub("/+$", "")
    local is_darwin = platform_name(options.platform) == "Darwin"
    local valid, validation_err = validate_stage(
        stage, is_darwin, options.image_validator or validate_image)
    if not valid then return nil, validation_err end

    local abi_dir = join(root, "lib/titan/0.16")
    local shim_dir = join(root, "share/lua/5.5/titan")
    local lua_cdir = join(root, "lib/lua/5.5")
    local entries = {}
    local seen = {}

    for _, module in ipairs(MODULES) do
        add_entry(entries, seen, join(shim_dir, module .. ".lua"),
            join(stage, "titan/" .. module .. ".lua"), "file",
            "shim-" .. module)
    end
    add_entry(entries, seen, join(abi_dir, "titan.so.dSYM"),
        is_darwin and join(stage, "titan.so.dSYM") or nil,
        is_darwin and "directory" or nil, "dsym")

    local stale = {}
    for _, module in ipairs(MODULES) do
        for _, path in ipairs({
            join(abi_dir, "titan/" .. module .. ".so"),
            join(abi_dir, module .. ".so"),
            join(lua_cdir, "titan/" .. module .. ".so"),
            join(lua_cdir, "titan/stdlib_0_16/" .. module .. ".so"),
        }) do
            stale[#stale + 1] = path
            stale[#stale + 1] = path .. ".dSYM"
        end
    end
    stale[#stale + 1] = join(lua_cdir, "titan.so")
    stale[#stale + 1] = join(lua_cdir, "titan.so.dSYM")
    for index, path in ipairs(stale) do
        add_entry(entries, seen, path, nil, nil, "stale-" .. index)
    end

    -- The DSO is intentionally last: its rename commits the new public set.
    add_entry(entries, seen, join(abi_dir, "titan.so"),
        join(stage, "titan.so"), "executable", "dso")

    local prepared = {}
    local function clean_prepared()
        for _, entry in ipairs(entries) do
            if entry.prepared then remove_path(entry.prepared) end
        end
    end
    local function rollback()
        for index = #entries, 1, -1 do
            local entry = entries[index]
            if entry.committed then remove_path(entry.public) end
            if entry.backup then
                ensure_parent(entry.public)
                os.rename(entry.backup, entry.public)
            end
        end
        clean_prepared()
    end

    local prepared_ok, prepared_err = xpcall(function()
        for _, entry in ipairs(entries) do
            if entry.source then
                assert(ensure_parent(entry.public))
                entry.prepared = unique_sibling(entry.public, "new")
                assert(copy_tree(entry.source, entry.prepared))
                if entry.mode == "executable" then
                    assert(make_executable(entry.prepared))
                end
                prepared[#prepared + 1] = entry
            end
        end
    end, debug.traceback)
    if not prepared_ok then
        clean_prepared()
        return nil, prepared_err
    end

    local committed, commit_err = xpcall(function()
        -- Back up every old public/stale entry before committing any new one.
        for _, entry in ipairs(entries) do
            if lfs.symlinkattributes(entry.public, "mode") then
                entry.backup = unique_sibling(entry.public, "old")
                assert(os.rename(entry.public, entry.backup))
            end
        end

        for _, entry in ipairs(entries) do
            failpoint("before", entry.label)
            if entry.prepared then
                assert(os.rename(entry.prepared, entry.public))
                entry.prepared = nil
                entry.committed = true
            end
            failpoint("after", entry.label)
        end
    end, debug.traceback)
    if not committed then
        rollback()
        return nil, commit_err
    end

    -- The DSO commit succeeded. Backup removal is best effort and cannot turn
    -- the coherent new install into a reported hook failure.
    for _, entry in ipairs(entries) do
        if entry.backup then remove_path(entry.backup); entry.backup = nil end
    end
    clean_prepared()
    return true
end

installer.MODULES = MODULES
installer.BANNER = BANNER
installer.validate_image = validate_image

if direct then
    local ok, err =
        installer.publish({ stage = cli_stage, root = cli_root })
    if not ok then
        io.stderr:write(tostring(err), "\n")
        os.exit(1)
    end
end

return installer
