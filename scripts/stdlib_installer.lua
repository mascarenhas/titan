local BANNER = "-- Generated by titanc; do not edit.\n"
local MODULE_NAMES = {}
local MODULE_SET = {}
for _, module in ipairs(MODULES) do
    local name = "titan." .. module
    MODULE_NAMES[#MODULE_NAMES + 1] = name
    MODULE_SET[name] = true
end

local SHIM_TEMPLATE = [[local path, search_error = package.searchpath(%q, package.cpath)
if not path then error(search_error, 0) end

local titan = require "titan"
local open, open_error = titan._loadlibglobal(path, %q)
if not open then error(open_error, 0) end

return open()
]]

local function shim_contents(modname)
    local entry = "luaopen_" .. modname:gsub("[%-.]", "_")
    return BANNER .. string.format(SHIM_TEMPLATE, "titan", entry)
end

local function shim_relative_path(modname)
    if type(modname) ~= "string" or modname == "" then return nil end
    local components = {}
    for component in modname:gmatch("[^.]+") do
        if component == "" or component == "." or component == ".." or
           component:find("[/\\%z]") then
            return nil
        end
        components[#components + 1] = component
    end
    if #components == 0 or table.concat(components, ".") ~= modname then
        return nil
    end
    return table.concat(components, "/") .. ".lua"
end

local function join(root, suffix)
    if root == "/" then return "/" .. suffix end
    return root:gsub("/+$", "") .. "/" .. suffix
end

local function ensure_directory(path, created)
    local mode = lfs.symlinkattributes(path, "mode")
    if mode == "directory" then return true end
    if mode then return nil, "path '" .. path .. "' is not a directory" end
    local parent = path:match("^(.*)/[^/]+$")
    if parent and parent ~= "" then
        local ok, err = ensure_directory(parent, created)
        if not ok then return nil, err end
    end
    local ok, err = lfs.mkdir(path)
    if ok then
        if created then created[#created + 1] = path end
        return true
    end
    if lfs.symlinkattributes(path, "mode") == "directory" then return true end
    return nil, err
end

local function ensure_parent(path, created)
    local parent = path:match("^(.*)/[^/]+$")
    if not parent or parent == "" then return true end
    return ensure_directory(parent, created)
end

local function remove_path(path)
    local mode = lfs.symlinkattributes(path, "mode")
    if mode == "directory" then
        for name in lfs.dir(path) do
            if name ~= "." and name ~= ".." then
                local ok, err = remove_path(path .. "/" .. name)
                if not ok then return nil, err end
            end
        end
        return lfs.rmdir(path)
    elseif mode then
        return os.remove(path)
    end
    return true
end

local function copy_file(source, destination)
    local input, input_err = io.open(source, "rb")
    if not input then return nil, input_err end
    local output, output_err = io.open(destination, "wb")
    if not output then input:close(); return nil, output_err end
    while true do
        local block = input:read(1024 * 1024)
        if not block then break end
        local ok, err = output:write(block)
        if not ok then
            input:close()
            output:close()
            return nil, err
        end
    end
    local input_ok, input_close_err = input:close()
    local output_ok, output_close_err = output:close()
    if not input_ok then return nil, input_close_err end
    if not output_ok then return nil, output_close_err end
    return true
end

local function copy_tree(source, destination)
    local mode = lfs.symlinkattributes(source, "mode")
    if mode == "file" then return copy_file(source, destination) end
    if mode ~= "directory" then
        return nil, "staged path '" .. source .. "' has unsupported type " ..
            tostring(mode)
    end
    local ok, err = ensure_directory(destination)
    if not ok then return nil, err end
    for name in lfs.dir(source) do
        if name ~= "." and name ~= ".." then
            ok, err = copy_tree(source .. "/" .. name,
                destination .. "/" .. name)
            if not ok then return nil, err end
        end
    end
    return true
end

local function read_file(path)
    local file, err = io.open(path, "rb")
    if not file then return nil, err end
    local contents = file:read("*a")
    file:close()
    return contents
end

local function shell_quote(word)
    return "'" .. word:gsub("'", "'\\''") .. "'"
end

local function set_permissions(path, permissions)
    local ok, why, code =
        os.execute("chmod " .. permissions .. " " .. shell_quote(path))
    if ok then return true end
    return nil, "chmod failed for '" .. path .. "' (" .. tostring(why) ..
        (code and (", " .. tostring(code)) or "") .. ")"
end

local function unique_sibling(path, kind)
    local seed = os.tmpname()
    os.remove(seed)
    seed = seed:match("([^/]+)$") or seed:gsub("[^%w]", "_")
    return path .. ".titan-install-" .. kind .. "." .. seed
end

local function platform_name(explicit)
    if explicit and explicit ~= "" then return explicit end
    local pipe = io.popen("uname", "r")
    if not pipe then return "unknown" end
    local value = pipe:read("*a") or ""
    pipe:close()
    return value:match("^%s*(.-)%s*$")
end

local IMAGE_INSPECTOR = [[
local image, result = ...
local modules = { select(3, ...) }

local function finish(ok, message)
    local out = assert(io.open(result, "wb"))
    out:write(message)
    out:close()
    os.exit(ok and 0 or 1)
end

local function one_string(fn, label)
    local values = table.pack(pcall(fn))
    if not values[1] then
        finish(false, label .. " failed: " .. tostring(values[2]))
    end
    if values.n ~= 2 or type(values[2]) ~= "string" then
        finish(false, label .. " must return exactly one string")
    end
    return values[2]
end

local support_open, support_error =
    package.loadlib(image, "luaopen_titan")
if not support_open then
    finish(false, "image is missing luaopen_titan: " ..
        tostring(support_error))
end
local support_values = table.pack(pcall(support_open))
if not support_values[1] or support_values.n ~= 2 or
   type(support_values[2]) ~= "table" or
   type(support_values[2]._loadlib) ~= "function" or
   type(support_values[2]._loadlibglobal) ~= "function" then
    finish(false, "luaopen_titan does not return the required native support table")
end
local loadlib = support_values[2]._loadlib
local entries = {}
for _, modname in ipairs(modules) do
    local prefix = modname:gsub("[%-.]", "_")
    local abi, abi_error = loadlib(image, prefix .. "_abi")
    if not abi then
        finish(false, "image is missing " .. prefix .. "_abi: " ..
            tostring(abi_error))
    end
    local typefn, type_error = loadlib(image, prefix .. "_types")
    if not typefn then
        finish(false, "image is missing " .. prefix .. "_types: " ..
            tostring(type_error))
    end
    for _, symbol in ipairs({
        prefix .. "_init",
        "luaopen_" .. prefix,
    }) do
        local entry, entry_error = loadlib(image, symbol)
        if not entry then
            finish(false, "image is missing " .. symbol .. ": " ..
                tostring(entry_error))
        end
    end
    entries[modname] = {
        abi = one_string(abi, prefix .. "_abi"),
        types = one_string(typefn, prefix .. "_types"),
    }
end

local out = assert(io.open(result, "wb"))
out:write("return {\n")
for _, modname in ipairs(modules) do
    local entry = entries[modname]
    out:write("[", string.format("%q", modname), "]={abi=",
        string.format("%q", entry.abi), ",types=",
        string.format("%q", entry.types), "},\n")
end
out:write("}\n")
out:close()
]]

local function current_lua(root, explicit)
    if explicit and explicit ~= "" then return explicit end
    local installed = root and join(root, "bin/lua")
    if installed and lfs.symlinkattributes(installed, "mode") == "file" then
        return installed
    end
    if type(arg) == "table" and type(arg[-1]) == "string" and
       lfs.symlinkattributes(arg[-1], "mode") == "file" then
        return arg[-1]
    end
    return "lua"
end

local function inspect_image(image, module_names, options)
    options = options or {}
    local script = unique_sibling(image, "inspect.lua")
    local result = unique_sibling(image, "inspect.result")
    local output, output_err = io.open(script, "wb")
    if not output then return nil, output_err end
    local wrote, write_err = output:write(IMAGE_INSPECTOR)
    local closed, close_err = output:close()
    if not wrote then os.remove(script); return nil, write_err end
    if not closed then os.remove(script); return nil, close_err end

    local words = {
        shell_quote(current_lua(options.root, options.lua)),
        "-E", shell_quote(script), shell_quote(image), shell_quote(result),
    }
    for _, name in ipairs(module_names) do
        words[#words + 1] = shell_quote(name)
    end
    local ok, why, code = os.execute(table.concat(words, " "))
    local contents = read_file(result)
    os.remove(script)
    os.remove(result)
    if not ok then
        return nil, "cannot inspect native image '" .. image .. "': " ..
            tostring(contents or why) ..
            (code and (" (exit " .. tostring(code) .. ")") or "")
    end
    local chunk, load_err = load(
        contents or "", "=Titan native image inspection", "t", {})
    if not chunk then return nil, load_err end
    local values = table.pack(pcall(chunk))
    if not values[1] then return nil, tostring(values[2]) end
    if values.n ~= 2 or type(values[2]) ~= "table" then
        return nil, "native image inspection returned invalid results"
    end
    local entries = values[2]
    for _, name in ipairs(module_names) do
        local entry = entries[name]
        if type(entry) ~= "table" or type(entry.abi) ~= "string" or
           type(entry.types) ~= "string" then
            return nil, "native image inspection omitted module '" ..
                name .. "'"
        end
        if entry.abi ~= driver.TITAN_VER then
            return nil, "native image ABI for module '" .. name ..
                "' is " .. tostring(entry.abi) .. " instead of " ..
                driver.TITAN_VER
        end
        local decoded, decode_err = driver.decode_module_interface(
            entry.types, name, image)
        if not decoded then
            return nil, "native image types for module '" .. name ..
                "' are invalid: " .. tostring(decode_err)
        end
    end
    for name in pairs(entries) do
        if not MODULE_SET[name] then
            return nil, "native image inspection returned unexpected module '" ..
                tostring(name) .. "'"
        end
    end
    return entries
end

local function scan_archive(archive)
    return staticmetadata.scan_archive(archive, {
        expected_abi = driver.TITAN_VER,
        validate_types = function(name, serialized, origin)
            return driver.decode_module_interface(serialized, name, origin)
        end,
    })
end

local function require_exact_keys(entries, module_names, subject)
    local expected = {}
    for _, name in ipairs(module_names) do expected[name] = true end
    for name in pairs(entries or {}) do
        if not expected[name] then
            return nil, subject .. " has unexpected logical key '" ..
                tostring(name) .. "'"
        end
        expected[name] = nil
    end
    local missing = next(expected)
    if missing then
        return nil, subject .. " is missing logical key '" .. missing .. "'"
    end
    return true
end

local function compare_entries(actual, expected, subject)
    for name, found in pairs(actual or {}) do
        local wanted = expected and expected[name]
        if not wanted then
            return nil, subject .. " logical key set differs at module '" ..
                tostring(name) .. "'"
        end
        if found.abi ~= wanted.abi then
            return nil, subject .. " ABI for module '" .. name ..
                "' differs: expected " .. tostring(wanted.abi) ..
                " but found " .. tostring(found.abi)
        end
        if found.types ~= wanted.types then
            return nil, subject .. " type metadata for module '" .. name ..
                "' differs"
        end
    end
    for name in pairs(expected or {}) do
        if not actual[name] then
            return nil, subject .. " logical key set differs at module '" ..
                tostring(name) .. "'"
        end
    end
    return true
end

local function validate_native_pair(dso, archive, module_names, options)
    options = options or {}
    local image_inspector =
        options.native_image_inspector or inspect_image
    local archive_scanner =
        options.staged_archive_scanner or scan_archive
    local validation_builder =
        options.archive_validation_builder or
        driver.compile_archive_validation_image
    local dso_entries, dso_err =
        image_inspector(dso, module_names, options)
    if not dso_entries then return nil, dso_err end

    local provider, scan_err = archive_scanner(archive)
    if not provider then
        return nil, "cannot inspect staged titan.a: " .. tostring(scan_err)
    end
    local keys_ok, keys_err = require_exact_keys(
        provider.entries, module_names, "staged titan.a")
    if not keys_ok then return nil, keys_err end
    local agrees, agreement_err = compare_entries(
        provider.entries, dso_entries,
        "staged titan.a versus staged titan.so")
    if not agrees then return nil, agreement_err end

    local validation_image = unique_sibling(dso, "archive-validation")
    local function clean_validation_image()
        remove_path(validation_image)
        remove_path(validation_image .. ".dSYM")
    end
    local completed, validation_or_err = xpcall(function()
        local linked, term, code = validation_builder(
            validation_image, archive, nil, false)
        if not linked then
            error("cannot link staged titan.a validation image: " ..
                tostring(term) ..
                (code and (" (exit " .. tostring(code) .. ")") or ""), 0)
        end
        local archive_entries, inspect_err =
            image_inspector(validation_image, module_names, options)
        if not archive_entries then error(inspect_err, 0) end
        local archive_agrees, archive_agreement_err =
            compare_entries(
                provider.entries, archive_entries,
                "staged titan.a embedded metadata versus callable protocols")
        if not archive_agrees then error(archive_agreement_err, 0) end
        local pair_agrees, pair_agreement_err =
            compare_entries(
                dso_entries, archive_entries,
                "staged titan.so versus archive-backed validation image")
        if not pair_agrees then error(pair_agreement_err, 0) end
        return true
    end, debug.traceback)
    clean_validation_image()
    if not completed then return nil, validation_or_err end
    return true
end

local function validate_stage(stage, is_darwin, image_validator, options)
    local dso = join(stage, "titan.so")
    local archive = join(stage, "titan.a")
    if lfs.symlinkattributes(dso, "mode") ~= "file" then
        return nil, "staged standard library has no regular titan.so"
    end
    if lfs.symlinkattributes(archive, "mode") ~= "file" then
        return nil, "staged standard library has no regular titan.a"
    end
    if is_darwin and
       lfs.symlinkattributes(dso .. ".dSYM", "mode") ~= "directory" then
        return nil, "staged macOS standard library has no titan.so.dSYM"
    end
    local image_ok, image_err =
        image_validator(dso, archive, MODULE_NAMES, options)
    if not image_ok then return nil, image_err end
    for _, module in ipairs(MODULES) do
        local path = join(stage, "titan/" .. module .. ".lua")
        if lfs.symlinkattributes(path, "mode") ~= "file" then
            return nil, "staged standard library has no regular shim '" ..
                path .. "'"
        end
        local contents, err = read_file(path)
        if not contents then return nil, err end
        if contents ~= shim_contents("titan." .. module) then
            return nil, "staged shim '" .. path ..
                "' does not match titanc's generated provider/entry template"
        end
    end
    return true
end

local function add_entry(entries, seen, public, source, mode, label)
    if seen[public] then return end
    seen[public] = true
    entries[#entries + 1] = {
        public = public,
        source = source,
        mode = mode,
        label = label,
    }
end

local function failpoint(position, label)
    local requested = os.getenv("TITAN_INSTALL_FAIL_AT")
    if requested == position .. ":" .. label then
        error("injected standard-library publication failure at " ..
            requested, 0)
    end
end

local function validate_public_native_destination(path)
    local mode = lfs.symlinkattributes(path, "mode")
    if mode and mode ~= "file" then
        return nil, "public native destination '" .. path ..
            "' is not a regular nonlink file"
    end
    return true
end

local function validate_public_shim(path, modname)
    local mode = lfs.symlinkattributes(path, "mode")
    if not mode then return true end
    if mode ~= "file" then
        return nil, "public generated shim '" .. path ..
            "' is not a regular nonlink file"
    end
    local contents, read_err = read_file(path)
    if not contents then return nil, read_err end
    if contents ~= shim_contents(modname) then
        return nil, "refusing to overwrite unrecognized Lua file '" ..
            path .. "'"
    end
    return true
end

local function valid_prior_archive_entries(path, scanner)
    if lfs.symlinkattributes(path, "mode") ~= "file" then return {} end
    local called, provider = pcall(scanner, path)
    if not called or type(provider) ~= "table" or
       type(provider.entries) ~= "table" then
        -- A regular pre-feature or corrupt archive has no trustworthy
        -- enumerable ownership set. It remains replaceable, but it cannot
        -- authorize broad shim retirement.
        return {}
    end
    return provider.entries
end

function installer.publish(options)
    options = options or {}
    local stage = assert(options.stage, "missing staged standard-library root")
    local root = assert(options.root, "missing Titan rocks tree")
    if stage:sub(1, 1) ~= "/" or root:sub(1, 1) ~= "/" then
        return nil, "staging and rocks-tree paths must be absolute"
    end
    stage = stage:gsub("/+$", "")
    root = root:gsub("/+$", "")
    local test_source = join(stage, "titan/test.titan")
    if lfs.symlinkattributes(test_source, "mode") ~= "file" then
        return nil, "standard-library publication has no regular titan.test " ..
            "support source '" .. test_source .. "'"
    end
    local is_darwin = platform_name(options.platform) == "Darwin"
    local valid, validation_err = validate_stage(
        stage, is_darwin,
        options.image_validator or validate_native_pair, options)
    if not valid then return nil, validation_err end

    local abi_dir = join(root, "lib/titan/0.24")
    local shim_dir = join(root, "share/lua/5.5/titan")
    local shim_root = join(root, "share/lua/5.5")
    local lua_cdir = join(root, "lib/lua/5.5")
    local public_dso = join(abi_dir, "titan.so")
    local public_archive = join(abi_dir, "titan.a")
    local public_test_source =
        join(root, "share/titan/0.24/src/titan/test.titan")

    local destination_ok, destination_err =
        validate_public_native_destination(public_dso)
    if not destination_ok then return nil, destination_err end
    destination_ok, destination_err =
        validate_public_native_destination(public_archive)
    if not destination_ok then return nil, destination_err end
    destination_ok, destination_err =
        validate_public_native_destination(public_test_source)
    if not destination_ok then return nil, destination_err end
    for _, module in ipairs(MODULES) do
        local path = join(shim_dir, module .. ".lua")
        local shim_ok, shim_err =
            validate_public_shim(path, "titan." .. module)
        if not shim_ok then return nil, shim_err end
    end

    local entries = {}
    local seen = {}

    for _, module in ipairs(MODULES) do
        add_entry(entries, seen, join(shim_dir, module .. ".lua"),
            join(stage, "titan/" .. module .. ".lua"), "file",
            "shim-" .. module)
    end
    add_entry(entries, seen, public_test_source, test_source, "file",
        "test-source")
    add_entry(entries, seen, join(abi_dir, "titan.so.dSYM"),
        is_darwin and join(stage, "titan.so.dSYM") or nil,
        is_darwin and "directory" or nil, "dsym")

    -- A valid old self-describing archive is the only authority for retiring
    -- generated shims which no longer belong to this provider. Never scan the
    -- public Lua tree or infer ownership from a bootstrap-only predecessor.
    local prior_entries = valid_prior_archive_entries(
        public_archive, options.prior_archive_scanner or scan_archive)
    local retired_names = {}
    for name in pairs(prior_entries) do
        if not MODULE_SET[name] then retired_names[#retired_names + 1] = name end
    end
    table.sort(retired_names)
    for _, name in ipairs(retired_names) do
        local relative = shim_relative_path(name)
        if not relative then
            return nil, "prior titan.a contains module '" .. tostring(name) ..
                "' with no safe generated shim path"
        end
        local path = join(shim_root, relative)
        local shim_ok, shim_err = validate_public_shim(path, name)
        if not shim_ok then return nil, shim_err end
        if lfs.symlinkattributes(path, "mode") then
            add_entry(entries, seen, path, nil, nil,
                "retired-shim-" .. name:gsub("[^%w]+", "-"))
        end
    end

    local stale = {}
    for _, module in ipairs(MODULES) do
        for _, path in ipairs({
            join(abi_dir, "titan/" .. module .. ".so"),
            join(abi_dir, module .. ".so"),
            join(lua_cdir, "titan/" .. module .. ".so"),
            join(lua_cdir, "titan/stdlib_0_24/" .. module .. ".so"),
        }) do
            stale[#stale + 1] = path
            stale[#stale + 1] = path .. ".dSYM"
        end
    end
    stale[#stale + 1] = join(lua_cdir, "titan.so")
    stale[#stale + 1] = join(lua_cdir, "titan.so.dSYM")
    for index, path in ipairs(stale) do
        add_entry(entries, seen, path, nil, nil, "stale-" .. index)
    end

    -- The archive is published after shims/dSYM and before the DSO commit
    -- point. A caught failure at either native artifact restores the exact
    -- supported bootstrap-only or prior-pair state.
    add_entry(entries, seen, public_archive,
        join(stage, "titan.a"), "file", "titan.a")

    -- The DSO is intentionally last: its rename commits the new public set.
    add_entry(entries, seen, public_dso,
        join(stage, "titan.so"), "executable", "titan.so")

    local created_directories = {}
    local function clean_prepared()
        for _, entry in ipairs(entries) do
            if entry.prepared then remove_path(entry.prepared) end
        end
    end
    local function clean_created_directories()
        for index = #created_directories, 1, -1 do
            -- A successful publication owns these parents. On failure, remove
            -- only newly created parents which are still empty after rollback.
            lfs.rmdir(created_directories[index])
        end
    end
    local function rollback()
        for index = #entries, 1, -1 do
            local entry = entries[index]
            if entry.committed then remove_path(entry.public) end
            if entry.backup then
                ensure_parent(entry.public)
                os.rename(entry.backup, entry.public)
            end
        end
        clean_prepared()
        clean_created_directories()
    end

    local prepared_ok, prepared_err = xpcall(function()
        for _, entry in ipairs(entries) do
            if entry.source then
                assert(ensure_parent(entry.public, created_directories))
                entry.prepared = unique_sibling(entry.public, "new")
                assert(copy_tree(entry.source, entry.prepared))
                if entry.mode == "executable" then
                    assert(set_permissions(entry.prepared, "0755"))
                elseif entry.mode == "file" then
                    assert(set_permissions(entry.prepared, "0644"))
                end
            end
        end
    end, debug.traceback)
    if not prepared_ok then
        clean_prepared()
        clean_created_directories()
        return nil, prepared_err
    end

    local committed, commit_err = xpcall(function()
        -- Back up every old public/stale entry before committing any new one.
        for _, entry in ipairs(entries) do
            if lfs.symlinkattributes(entry.public, "mode") then
                entry.backup = unique_sibling(entry.public, "old")
                assert(os.rename(entry.public, entry.backup))
            end
        end

        for _, entry in ipairs(entries) do
            failpoint("before", entry.label)
            if entry.prepared then
                assert(os.rename(entry.prepared, entry.public))
                entry.prepared = nil
                entry.committed = true
            end
            failpoint("after", entry.label)
        end
    end, debug.traceback)
    if not committed then
        rollback()
        return nil, commit_err
    end

    -- The DSO commit succeeded. Backup removal is best effort and cannot turn
    -- the coherent new install into a reported hook failure.
    for _, entry in ipairs(entries) do
        if entry.backup then remove_path(entry.backup); entry.backup = nil end
    end
    clean_prepared()
    return true
end

