-- Browser standard-library operation-status inventory. The maintainer reviews
-- every change to this file; scripts/browser_stdlib.lua checks it against the
-- installed native and browser providers.
--
-- `modules` has a row for every native module and every browser-only module:
--   present       delivered on the browser; `test` names its test owner, and
--                 `core` marks the dependency-free core modules
--   absent        not available on the browser; `reason` completes the
--                 compiler's "not available for target 'browser'" diagnostic
--   browser-only  no native counterpart (exempt from the parity comparison)
--
-- `members` has a row for every public callable, type and variable of a
-- present module, as `{ name, status, test }`. Fields, union variants and
-- Interface methods belong to their owner's row.
--   implemented         works with its native meaning; `test` exercises it
--   raise               every call raises the member-qualified unavailable error
--   type-only           kept only as a type: nothing but a `raise` member can
--                       produce a value; no test (the parity gate checks it)
--   absent:typed        its declaration names an absent module; no test
--   absent:native-only  no honest browser meaning; no test
--
-- A test is `<owner>.<case>` as the runner reports it (subtests joined with
-- `.`), `os.browser_tests:<name>` for a case of the program-mode OS stream
-- harness, or, for implemented members of core modules only, a whole
-- `<owner>`.
--
-- `stock_lua` has a row for every operation group of the stock Lua profile
-- that the browser opens in every state.
