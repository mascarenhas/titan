// A recorded change, [kind, ...fields]. A node is named by its inode number,
// its id, which the guest allocates even and the worker odd, so one id names
// the same node in both trees. `hold` and `release` tell the other side that
// this side opened a file's first handle or closed its last; the other side
// keeps a handle of its own open meanwhile, so an unlinked file and its
// stored bytes live on both sides while either side holds it.
const op = Object.freeze({create: 1, link: 2, unlink: 3, rename: 4, write: 5, resize: 6, times: 7, sync: 8, hold: 9,
  release: 10});
const fsErrno = Object.freeze({busy: 10, nospc: 51, notsup: 58, xdev: 75});

function idOf(node) { return Number(node.ino); }

// The FSBackend of one namespace. It routes each node to its mount's backend,
// indexes nodes by id, counts this side's open handles and holds the other
// side's, and counts the file bytes resident in durable mounts. While
// `journal` is an array it appends each change to it as an op, and admits
// durable growth only within `limit` resident bytes and, when set, the
// remaining `allowance`. While `undoable`, each namespace change keeps how
// to undo it, under its op (or `current`, the op being redone). When
// `unflushed` is a Set, it holds the durable files written since their last
// flush.
class StorageBackend {
  constructor(fileSystem, limit) {
    this.memory = fileSystem.backend;
    this.nodes = new Map();
    this.mounts = new WeakMap();
    this.pinned = new WeakSet();
    this.open = new Map();
    this.remote = new Map();
    this.dead = new Map();
    this.unnamed = [];
    this.journal = null;
    this.recorded = undefined;
    this.unflushed = null;
    this.limit = limit;
    this.allowance = undefined;
    this.resident = 0;
    this.batch = false;
    this.undoable = false;
    this.undos = new WeakMap();
    this.current = undefined;
    this.index(fileSystem.lookup('/'));
  }

  // Adds `node` and its subtree, as part of `mount` ({root, backend, durable}).
  index(node, mount) {
    this.nodes.set(idOf(node), node);
    if (mount) this.mounts.set(node, mount);
    this.resident += this.bytes(node);
    if (node.type === 'dir') for (const name in node.entries) this.index(node.entries[name], mount);
  }

  // Makes `mount.root`, the directory at `path`, a mount; the directories
  // above it stay where they are.
  mount(fileSystem, path, mount) {
    for (let at = path.indexOf('/', 1); at > 0; at = path.indexOf('/', at + 1)) {
      this.pinned.add(fileSystem.lookup(path.slice(0, at)));
    }
    this.index(mount.root, mount);
  }

  backend(node) { return this.mounts.get(node)?.backend ?? this.memory; }

  durable(node) { return this.mounts.get(node)?.durable === true; }

  bytes(node) { return node.type === 'file' && this.durable(node) ? this.fileSize(node) : 0; }

  record(entry) {
    this.journal.push(entry);
    this.recorded?.(entry);
  }

  // How to put back the names (`dirents`, [dir, name]) and the link counts
  // and liveness of `nodes` a namespace change is about to alter. A node the
  // change creates goes back to having no name.
  saved(dirents, nodes) {
    if (!this.undoable) return undefined;
    const names = dirents.map(([dir, name]) => [dir, name, dir.entries[name]]);
    const states = nodes.filter(Boolean).map(node =>
      [node, node.nlink, this.dead.has(node), this.nodes.get(idOf(node)) === node]);
    return () => {
      for (const [node, nlink, dead, known] of states) {
        if (node.type !== 'dir') node.nlink = known ? nlink : 0;
        if (dead || !known) this.dead.set(node, this.bytes(node));
        else this.dead.delete(node);
      }
      for (const [dir, name, prior] of names.reverse()) {
        if (prior) dir.entries[name] = prior;
        else delete dir.entries[name];
      }
    };
  }

  // Records a namespace change and keeps its undo.
  note(entry, restore) {
    if (this.journal) this.record(entry);
    const owner = this.journal ? entry : this.current;
    if (!restore || !owner) return;
    const list = this.undos.get(owner);
    if (list) list.push(restore);
    else this.undos.set(owner, [restore]);
  }

  // A node that lost a name in the previous call goes once that call has
  // updated the tree, unless something still holds it.
  reap() {
    while (this.unnamed.length) this.prune(this.unnamed.pop());
  }

  // Dead files still count until pruned, so a full store prunes first.
  admit(node, growth) {
    if (!this.journal || growth <= 0 || !this.durable(node)) return;
    const fits = () => growth <= Math.min(this.limit - this.resident, this.allowance ?? Infinity);
    if (!fits()) this.prune();
    if (!fits()) throw new FSError(fsErrno.nospc);
  }

  grow(node, growth) {
    if (!growth || !this.durable(node)) return;
    this.resident += growth;
    if (this.journal && this.allowance !== undefined && growth > 0) this.allowance -= growth;
  }

  // A mount root, and each directory above one, stays where it is; no name
  // crosses a mount.
  check(node, from, to = from) {
    if (node && (this.mounts.get(node)?.root === node || this.pinned.has(node))) throw new FSError(fsErrno.busy);
    if (this.mounts.get(from) !== this.mounts.get(to)) throw new FSError(fsErrno.xdev);
  }

  // Drops each dead node (or just `only`) no name or handle on either side
  // holds; a dropped directory takes what it still holds with it. Nothing is
  // dropped while a batch of the other side's ops applies, or while a
  // statement in flight may still undo this side's recent changes.
  prune(only) {
    if (this.batch || this.undoable || only && !this.dead.has(only)) return;
    for (const [node, size] of only ? [[only, this.dead.get(only)]] : this.dead) {
      if (node.type !== 'dir' && node.nlink > 0) {
        this.dead.delete(node);
      } else if (!this.open.has(node) && !this.remote.has(node)) {
        this.dead.delete(node);
        this.nodes.delete(idOf(node));
        this.resident -= size;
        this.unflushed?.delete(node);
        for (const name in node.type === 'dir' ? node.entries : {}) {
          const child = node.entries[name];
          if (child.type !== 'dir') child.nlink--;
          this.dead.set(child, this.bytes(child));
        }
      }
    }
  }

  fileSize(node) { return this.backend(node).fileSize(node); }

  syncDirectory(dir) { this.backend(dir).syncDirectory(dir); }

  setTimes(node, atim, mtim) {
    if (this.journal) this.record([op.times, idOf(node), atim, mtim]);
  }

  createChild(parent, name, node) {
    this.reap();
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).createChild(parent, name, node);
    // A node named again after losing its name already counts.
    if (!this.dead.delete(node)) this.index(node, this.mounts.get(parent));
    this.note([op.create, idOf(parent), name, idOf(node), node.type, node.target ?? null, node.mtim], restore);
  }

  // A durable mount keeps one name per file, as the OPFS store does.
  linkChild(parent, name, node) {
    this.reap();
    this.check(undefined, parent, node);
    if (this.durable(parent)) throw new FSError(fsErrno.notsup);
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).linkChild(parent, name, node);
    this.note([op.link, idOf(parent), name, idOf(node)], restore);
  }

  removeChild(parent, name) {
    this.reap();
    const node = parent.entries[name], size = this.bytes(node);
    this.check(node, parent);
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).removeChild(parent, name);
    this.dead.set(node, size);
    this.unnamed.push(node);
    this.note([op.unlink, idOf(parent), name, idOf(node)], restore);
  }

  renameChild(from, fromName, to, toName) {
    this.reap();
    const node = from.entries[fromName], replaced = to.entries[toName];
    const size = replaced && replaced !== node ? this.bytes(replaced) : 0;
    this.check(node, from, to);
    if (replaced !== node) this.check(replaced, to);
    const restore = this.saved([[from, fromName], [to, toName]], [node, replaced]);
    this.backend(from).renameChild(from, fromName, to, toName);
    if (replaced && replaced !== node) {
      this.dead.set(replaced, size);
      this.unnamed.push(replaced);
    }
    this.note([op.rename, idOf(from), fromName, idOf(to), toName, idOf(node)], restore);
  }

  openFile(node, mode) {
    this.reap();
    const handle = this.backend(node).openFile(node, mode), id = idOf(node), count = this.open.get(node) ?? 0;
    this.open.set(node, count + 1);
    if (!count && this.journal) this.record([op.hold, id]);
    let closed = false;
    return {
      readAt: (buffer, offset) => handle.readAt(buffer, offset),
      writeAt: (data, offset) => {
        const size = this.fileSize(node);
        this.admit(node, offset + data.byteLength - size);
        const written = handle.writeAt(data, offset);
        this.grow(node, Math.max(0, offset + written - size));
        if (written > 0 && this.durable(node)) this.unflushed?.add(node);
        if (this.journal) this.record([op.write, id, offset, data.slice(0, written)]);
        return written;
      },
      resize: size => {
        const before = this.fileSize(node);
        this.admit(node, size - before);
        handle.resize(size);
        this.grow(node, size - before);
        if (this.durable(node)) this.unflushed?.add(node);
        if (this.journal) this.record([op.resize, id, size]);
      },
      sync: () => {
        handle.sync();
        this.unflushed?.delete(node);
        if (this.journal) this.record([op.sync, id]);
      },
      datasync: () => {
        handle.datasync();
        this.unflushed?.delete(node);
        if (this.journal) this.record([op.sync, id]);
      },
      close: () => {
        if (closed) return;
        closed = true;
        if (this.dead.has(node)) this.dead.set(node, this.bytes(node));
        const left = this.open.get(node) - 1;
        if (left) this.open.set(node, left);
        else this.open.delete(node);
        try { handle.close(); }
        finally {
          if (!left && this.journal) this.record([op.release, id]);
          if (!left && this.dead.has(node)) this.prune(node);
        }
      },
    };
  }
}

function materialize([, , , id, type, target, mtim]) {
  const now = mtim ?? nowNs(), node = type === 'dir' ? {type, entries: Object.create(null)} :
    type === 'file' ? {type, content: new Uint8Array(0), nlink: 1} :
    type === 'symlink' ? {type, target, nlink: 1} : {type, kind: 'devnull', nlink: 1};
  return Object.assign(node, {ino: BigInt(id), atim: now, mtim: now, ctim: now});
}

function unlink(storage, parent, name, node) {
  storage.removeChild(parent, name);
  delete parent.entries[name];
  if (node.type !== 'dir') node.nlink--;
}

// Applies a recorded op to `storage`'s tree as its syscall changed the tree
// that recorded it. An op that names a node this tree has dropped, or a name
// that no longer holds its node, changes nothing; a sync is the worker's.
function applyOp(storage, entry) {
  const {nodes} = storage, [kind, a, b, c] = entry;
  if (kind === op.create || kind === op.link) {
    // A create names a new node, or one that lost every name (a guest op
    // redone after a statement replaced it); a node still named elsewhere
    // was created already. A link names a known node once more.
    const parent = nodes.get(a), known = nodes.get(c);
    const fresh = !known || storage.dead.has(known) && !(known.nlink > 0);
    const node = kind === op.create ? fresh && (known ?? materialize(entry)) : known;
    if (parent?.type !== 'dir' || !node || parent.entries[b] === node) return;
    if (parent.entries[b]) unlink(storage, parent, b, parent.entries[b]);
    if (kind === op.create) storage.createChild(parent, b, node);
    else storage.linkChild(parent, b, node);
    parent.entries[b] = node;
    if (node.type !== 'dir') node.nlink = kind === op.create ? 1 : node.nlink + 1;
  } else if (kind === op.unlink) {
    const parent = nodes.get(a), node = nodes.get(c);
    if (node && parent?.entries[b] === node) unlink(storage, parent, b, node);
  } else if (kind === op.rename) {
    const [, , , , toName, id] = entry, from = nodes.get(a), to = nodes.get(c), node = nodes.get(id);
    if (!node || to?.type !== 'dir' || from?.entries[b] !== node) return;
    const replaced = to.entries[toName];
    storage.renameChild(from, b, to, toName);
    delete from.entries[b];
    to.entries[toName] = node;
    if (replaced && replaced !== node && replaced.type !== 'dir') replaced.nlink--;
  } else if (kind === op.hold || kind === op.release) {
    // This side's own handle keeps the file's stored bytes while the other
    // side holds it.
    const node = nodes.get(a), held = node && storage.remote.get(node);
    if (kind === op.hold && node?.type === 'file' && !held) {
      storage.remote.set(node, storage.backend(node).openFile(node, {read: true, write: false}));
    } else if (kind === op.release && held) {
      storage.remote.delete(node);
      held.close();
      storage.prune(node);
    }
  } else if (kind === op.times) {
    const node = nodes.get(a);
    if (!node) return;
    if (b != null) node.atim = b;
    if (c != null) node.mtim = c;
  } else if (kind !== op.sync && nodes.get(a)?.type === 'file') {
    const handle = storage.openFile(nodes.get(a), {read: false, write: true});
    try {
      if (kind === op.resize && b !== storage.fileSize(nodes.get(a))) handle.resize(b);
      // A short write (a full store) fails the op rather than truncating it.
      for (let at = 0; kind === op.write && at < c.byteLength;) {
        const written = handle.writeAt(c.subarray(at), b + at);
        if (written <= 0) throw new FSError(fsErrno.nospc);
        at += written;
      }
    } finally { handle.close(); }
  }
}
// storage core: end

// A module worker in a page, a worker_threads Worker under Node.
function spawnWorker(url, receive, fail) {
  const threads = globalThis.process?.getBuiltinModule?.('node:worker_threads');
  const worker = threads ? new threads.Worker(url.startsWith('file:') ? new URL(url) : url) :
    new Worker(url, {type: 'module'});
  if (threads) {
    worker.on('message', receive);
    worker.on('error', fail);
    worker.on('exit', () => fail(new Error('browser storage worker exited')));
  } else {
    worker.onmessage = event => receive(event.data);
    worker.onerror = event => fail(new Error(event.message || 'browser storage worker failed'));
  }
  return worker;
}

function revive({name, message, errno}) {
  return Object.assign(name === 'RangeError' ? new RangeError(message) : new Error(message), {name, errno});
}

const defaultLimit = 64 * 1048576;

// One instance's filesystem: the guest namespace its WASI imports and
// titan:vfs serve and, when it has durable mounts or links titan.sqlite3,
// the storage worker that mirrors that namespace. Every guest change is
// applied at once and journaled; the worker applies the journal in order and
// acknowledges it by sequence number, so its acknowledgement never rewrites
// a newer guest change.
class BrowserStorage {
  constructor(owner, options, image) {
    if (options !== undefined && (options === null || typeof options !== 'object')) {
      throw new TypeError('browser vfs must be an object');
    }
    const {mounts = {}, maxHydratedBytes = defaultLimit} = options ?? {};
    if (!Number.isSafeInteger(maxHydratedBytes) || maxHydratedBytes < 0) {
      throw new TypeError('browser vfs maxHydratedBytes must be a non-negative safe integer');
    }
    let next = 0;
    this.owner = owner;
    this.image = image;
    this.fileSystem = new uwasi.MemoryFileSystem(undefined, {allocateIno: () => BigInt(next += 2)});
    this.mounts = [];
    const paths = Object.keys(mounts);
    for (const path of paths) {
      const {backend, directory = 'titan' + path.replaceAll('/', '.')} = mounts[path] ?? {};
      if (!/^(\/[^/\0]+)+$/.test(path) || /\/\.\.?(\/|$)/.test(path) || /^\/dev(\/|$)/.test(path) ||
          paths.some(other => other.startsWith(path + '/'))) {
        throw new TypeError(`browser vfs mount ${path} must be a normalized absolute path outside /dev and other mounts`);
      }
      if (backend !== 'opfs' && backend !== 'memory') {
        throw new TypeError(`browser vfs mount ${path} needs backend "opfs" or "memory"`);
      }
      if (typeof directory !== 'string' || !/^[^/\\\0]+$/.test(directory) || directory === '.' || directory === '..') {
        throw new TypeError(`browser vfs mount ${path} directory must name one OPFS directory`);
      }
      this.fileSystem.ensureDir(backend === 'memory' ? path : path.slice(0, path.lastIndexOf('/')) || '/');
      this.mounts.push({path, backend, directory});
    }
    this.durable = this.mounts.filter(mount => mount.backend === 'opfs');
    for (const path of ['/tmp', '/home']) if (!this.durable.some(mount => mount.path === path)) this.fileSystem.ensureDir(path);
    this.sql = image.sql?.(this);
    this.vfs = this.source.bind(this);
    this.fds = this.worker = this.storage = undefined;
    this.pending = new Map();
    this.requests = 0;
    this.journal = [];
    this.base = 0;
    this.sent = 0;
    this.scheduled = false;
    this.statements = 0;
    this.cap = maxHydratedBytes;
    // Whether the worker last reported durable writes it has not flushed.
    this.unflushed = false;
    this.failure = undefined;
    this.lost = false;
    if (this.mounts.length || this.sql) {
      const storage = this.storage = new StorageBackend(this.fileSystem, maxHydratedBytes);
      for (const {path, backend} of this.mounts) {
        if (backend === 'memory') storage.mount(this.fileSystem, path, {root: this.fileSystem.lookup(path), backend: storage.memory, durable: false});
      }
      storage.recorded = () => this.schedule();
    }
  }

  // Before instantiation: start the worker, which opens the durable mounts
  // and the SQLite service, and graft each durable mount's tree, hydrated
  // whole.
  async start() {
    if (!this.durable.length && !this.sql) return;
    const {locateFile} = this.owner.options, {directory, worker, sqlite} = this.image, storage = this.storage;
    this.worker = spawnWorker(locateFile(worker, directory), message => this.receive(message),
      cause => this.terminate(cause));
    const root = this.fileSystem.lookup('/'), base = [];
    const walk = dir => {
      for (const name in dir.entries) {
        const node = dir.entries[name];
        base.push([op.create, idOf(dir), name, idOf(node), node.type, node.target ?? null, node.mtim]);
        if (node.type === 'dir') walk(node);
      }
    };
    walk(root);
    try {
      const {mounts} = await this.call({type: 'init', root: idOf(root), base, mounts: this.mounts, limit: storage.limit,
        sqlite: this.sql ? {url: locateFile(sqlite.wasm, directory), sha256: sqlite.sha256} : null});
      for (const {path, root: id, nodes} of mounts) {
        const slash = path.lastIndexOf('/'), node = materialize([0, 0, 0, id, 'dir']);
        this.fileSystem.lookup(path.slice(0, slash) || '/').entries[path.slice(slash + 1)] = node;
        storage.mount(this.fileSystem, path, {root: node, backend: storage.memory, durable: true});
        for (const entry of nodes) applyOp(storage, entry);
      }
    } catch (cause) {
      this.terminate(cause);
      throw cause;
    }
    storage.journal = this.journal;
  }

  // The image's WASI filesystem over this namespace. The standard streams,
  // descriptors 0 to 2, stay the factory's `base` ones.
  imports(context, base) {
    let view;
    const memory = () => view?.buffer === context.memory.buffer ? view : (view = new DataView(context.memory.buffer));
    const {syscalls, fds} = uwasi.bindFSSyscallsWithController(this.storage ?? this.fileSystem.backend,
      this.fileSystem, {}, new uwasi.WASIAbi(), memory);
    this.fds = fds;
    const wasi = Object.assign({}, base, syscalls);
    for (const name of ['fd_close', 'fd_fdstat_get', 'fd_fdstat_set_flags', 'fd_read', 'fd_seek', 'fd_write']) {
      wasi[name] = (fd, a, b, c) => (fd >>> 0 <= 2 ? base : syscalls)[name](fd, a, b, c);
    }
    wasi.fd_renumber = (from, to) => (from >>> 0 <= 2 || to >>> 0 <= 2 ? base : syscalls).fd_renumber(from, to);
    return {wasi, env: {
      titan_browser_vfs_linked: () => 1,
      titan_browser_vfs_retire_sync: (_state, fd) => this.retire(fd >>> 0),
      titan_browser_sql_retire_sync: (state, id) => this.sql?.retire(state >>> 0, BigInt.asUintN(64, id)),
    }};
  }

  // A closing state's File releases its descriptor without waiting; the
  // worker still flushes the file's last writes before it stops.
  retire(fd) {
    const node = this.fds.node(fd), status = this.fds.close(fd);
    if (status === 0 && this.storage?.durable(node) && this.storage.journal) this.storage.record([op.sync, idOf(node)]);
    return status;
  }

  // titan:vfs. `sync` settles once the worker holds every change made so far
  // and, for a descriptor of a durable file, has flushed that file. It
  // resolves to 0n, or to the WASI errno of the worker's storage failure as a
  // BigInt (a Titan integer); a stopped worker rejects.
  source(command, fd) {
    if (command !== 'sync') throw new TypeError(`unknown titan:vfs op ${command}`);
    const node = fd == null ? undefined : this.fds.node(Number(fd)), id = node && idOf(node);
    if (this.failure) return {kind: 'retained', promise: Promise.reject(this.failure)};
    if (!(node ? this.storage?.durable(node) : this.durable.length > 0)) return {kind: 'retained', promise: Promise.resolve(0n)};
    return {kind: 'retained', promise: this.call({type: 'sync', node: id}).then(() => 0n, cause => {
      if (!this.failure && Number.isInteger(cause?.errno) && cause.errno > 0) return BigInt(cause.errno);
      throw cause;
    })};
  }

  // titan:sqlite3's transport: one request frame to the worker's service,
  // run in the guest's working directory `cwd` when given. While statements
  // run, the guest may grow durable files by half the free bytes and the
  // statements by the other half, so neither side ever holds more than the
  // limit, and its namespace changes stay undoable. The reply carries the
  // file changes the statement made, applied here before the frame returns.
  dispatch(frame, cwd) {
    const storage = this.storage;
    if (!this.statements++) {
      storage.allowance = Math.floor(Math.max(0, storage.limit - storage.resident) / 2);
      storage.undoable = true;
      this.cap = storage.limit - storage.allowance;
    }
    const owned = frame.byteOffset || frame.byteLength !== frame.buffer.byteLength ? frame.slice() : frame;
    return this.call({type: 'sql', frame: owned, cwd, cap: this.cap}, [owned.buffer], this.base + this.journal.length);
  }

  closeState(state) { this.sql?.closeState(state); }

  call(message, transfer = [], mark) {
    if (this.failure) return Promise.reject(this.failure);
    this.flush();
    message.id = ++this.requests;
    const request = Promise.withResolvers();
    request.mark = mark;
    this.pending.set(message.id, request);
    this.worker.postMessage(message, transfer);
    return request.promise;
  }

  schedule() {
    if (this.scheduled) return;
    this.scheduled = true;
    queueMicrotask(() => this.flush());
  }

  // Posts the changes journaled since the last flush, in order.
  flush() {
    this.scheduled = false;
    if (this.sent < this.journal.length && !this.failure) {
      this.worker.postMessage({type: 'ops', ops: this.journal.slice(this.sent)});
      this.sent = this.journal.length;
    }
    this.storage?.prune();
  }

  // After a stop nothing the worker still sends applies. Each acknowledgement
  // and reply says whether the worker then held unflushed durable writes.
  receive(message) {
    if (this.failure) return;
    if (message.type === 'fatal') {
      this.terminate(revive(message.error));
      return;
    }
    this.unflushed = message.unflushed;
    if (message.type === 'ack') {
      this.journal.splice(0, message.seq - this.base);
      this.sent -= message.seq - this.base;
      this.base = message.seq;
      return;
    }
    const request = this.pending.get(message.id);
    this.pending.delete(message.id);
    if (request.mark !== undefined && !--this.statements) {
      this.storage.allowance = undefined;
      this.storage.undoable = false;
    }
    if (message.error) {
      request.reject(revive(message.error));
    } else if (request.mark === undefined) {
      request.resolve(message.value);
    } else {
      try {
        this.apply(message.value.deltas, request.mark);
        request.resolve(message.value.frame);
      } catch (cause) {
        this.terminate(cause);
        request.reject(cause);
      }
    }
  }

  // The worker ran a statement at the guest's change `mark`, then the guest's
  // later changes. The guest takes the same order: it undoes its later
  // namespace changes, applies the statement's changes to the tree as of
  // `mark`, then redoes its later changes. Content needs no undo: redoing
  // the later writes and resizes over the statement's leaves each file as
  // the worker has it.
  apply(deltas, mark) {
    const storage = this.storage, later = this.journal.slice(mark - this.base);
    storage.journal = null;
    storage.batch = true;
    try {
      for (let index = later.length; index--;) {
        for (const restore of (storage.undos.get(later[index]) ?? []).reverse()) restore();
        storage.undos.delete(later[index]);
      }
      for (const entry of deltas) applyOp(storage, entry);
      for (const entry of later) {
        storage.current = entry;
        if (entry[0] < op.sync) applyOp(storage, entry);
      }
    } finally {
      storage.current = undefined;
      storage.journal = this.journal;
      storage.batch = false;
    }
    storage.prune();
  }

  // The worker stops: nothing more reaches it. Changes it had not applied,
  // requests it had not answered, durable writes it had not flushed, whoever
  // made them, and an open SQLite write are lost.
  terminate(cause = new Error('browser storage worker was terminated')) {
    if (this.failure || !this.worker) return;
    this.failure = cause;
    this.lost = this.journal.length > 0 || this.pending.size > 0 || this.unflushed || this.sql?.transaction === true;
    this.storage.journal = null;
    this.worker.terminate();
    for (const request of this.pending.values()) request.reject(cause);
    this.pending.clear();
  }

  // Disposal: every connection left, transferred ones included, closes; the
  // worker applies, flushes and persists every change, then stops. Resolves
  // to whether an earlier forced stop lost changes. A disposed instance keeps
  // neither the guest's memory nor its files.
  async dispose() {
    try {
      if (this.worker && !this.failure) {
        this.sql?.retireAll();
        try {
          await this.call({type: 'dispose'});
        } catch (cause) {
          if (!this.failure) throw cause; // A forced stop meanwhile is lost work, not an error.
        } finally { this.terminate(); }
      }
      return this.lost;
    } finally {
      this.fds = this.fileSystem = this.storage = this.sql = this.owner = this.image = this.worker = undefined;
      this.journal = [];
    }
  }
}

/** The image binding's `storage`: the filesystem of one instance. */
export function titanBrowserStorage(owner, options, image) {
  return new BrowserStorage(owner, options, image);
}
