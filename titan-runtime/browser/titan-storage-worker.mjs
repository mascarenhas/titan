// A recorded change, [kind, ...fields]. A node is named by its inode number,
// its id, which the guest allocates even and the worker odd, so one id names
// the same node in both trees. `hold` and `release` tell the other side that
// this side opened a file's first handle or closed its last; the other side
// keeps a handle of its own open meanwhile, so an unlinked file and its
// stored bytes live on both sides while either side holds it.
const op = Object.freeze({create: 1, link: 2, unlink: 3, rename: 4, write: 5, resize: 6, sync: 7, hold: 8,
  release: 9});
const fsErrno = Object.freeze({busy: 10, nospc: 51, notsup: 58, xdev: 75});

function idOf(node) { return Number(node.ino); }

// The FSBackend of one namespace. It routes each node to its mount's backend,
// indexes nodes by id, counts this side's open handles and holds the other
// side's, and counts the file bytes resident in durable mounts. While
// `journal` is an array it appends each change to it as an op, and admits
// durable growth only within `limit` resident bytes and, when set, the
// remaining `allowance`. While `undoable`, each namespace change keeps how
// to undo it, under its op (or `current`, the op being redone). When
// `unflushed` is a Set, it holds the durable files written since their last
// flush.
class StorageBackend {
  constructor(fileSystem, limit) {
    this.memory = fileSystem.backend;
    this.nodes = new Map();
    this.mounts = new WeakMap();
    this.pinned = new WeakSet();
    this.open = new Map();
    this.remote = new Map();
    this.dead = new Map();
    this.unnamed = [];
    this.journal = null;
    this.recorded = undefined;
    this.unflushed = null;
    this.limit = limit;
    this.allowance = undefined;
    this.resident = 0;
    this.batch = false;
    this.undoable = false;
    this.undos = new WeakMap();
    this.current = undefined;
    this.index(fileSystem.lookup('/'));
  }

  // Adds `node` and its subtree, as part of `mount` ({root, backend, durable}).
  index(node, mount) {
    this.nodes.set(idOf(node), node);
    if (mount) this.mounts.set(node, mount);
    this.resident += this.bytes(node);
    if (node.type === 'dir') for (const name in node.entries) this.index(node.entries[name], mount);
  }

  // Makes `mount.root`, the directory at `path`, a mount; the directories
  // above it stay where they are.
  mount(fileSystem, path, mount) {
    for (let at = path.indexOf('/', 1); at > 0; at = path.indexOf('/', at + 1)) {
      this.pinned.add(fileSystem.lookup(path.slice(0, at)));
    }
    this.index(mount.root, mount);
  }

  backend(node) { return this.mounts.get(node)?.backend ?? this.memory; }

  durable(node) { return this.mounts.get(node)?.durable === true; }

  bytes(node) { return node.type === 'file' && this.durable(node) ? this.fileSize(node) : 0; }

  record(entry) {
    this.journal.push(entry);
    this.recorded?.(entry);
  }

  // How to put back the names (`dirents`, [dir, name]) and the link counts
  // and liveness of `nodes` a namespace change is about to alter. A node the
  // change creates goes back to having no name.
  saved(dirents, nodes) {
    if (!this.undoable) return undefined;
    const names = dirents.map(([dir, name]) => [dir, name, dir.entries[name]]);
    const states = nodes.filter(Boolean).map(node =>
      [node, node.nlink, this.dead.has(node), this.nodes.get(idOf(node)) === node]);
    return () => {
      for (const [node, nlink, dead, known] of states) {
        if (node.type !== 'dir') node.nlink = known ? nlink : 0;
        if (dead || !known) this.dead.set(node, this.bytes(node));
        else this.dead.delete(node);
      }
      for (const [dir, name, prior] of names.reverse()) {
        if (prior) dir.entries[name] = prior;
        else delete dir.entries[name];
      }
    };
  }

  // Records a namespace change and keeps its undo.
  note(entry, restore) {
    if (this.journal) this.record(entry);
    const owner = this.journal ? entry : this.current;
    if (!restore || !owner) return;
    const list = this.undos.get(owner);
    if (list) list.push(restore);
    else this.undos.set(owner, [restore]);
  }

  // A node that lost a name in the previous call goes once that call has
  // updated the tree, unless something still holds it.
  reap() {
    while (this.unnamed.length) this.prune(this.unnamed.pop());
  }

  // Dead files still count until pruned, so a full store prunes first.
  admit(node, growth) {
    if (!this.journal || growth <= 0 || !this.durable(node)) return;
    const fits = () => growth <= Math.min(this.limit - this.resident, this.allowance ?? Infinity);
    if (!fits()) this.prune();
    if (!fits()) throw new FSError(fsErrno.nospc);
  }

  grow(node, growth) {
    if (!growth || !this.durable(node)) return;
    this.resident += growth;
    if (this.journal && this.allowance !== undefined && growth > 0) this.allowance -= growth;
  }

  // A mount root, and each directory above one, stays where it is; no name
  // crosses a mount.
  check(node, from, to = from) {
    if (node && (this.mounts.get(node)?.root === node || this.pinned.has(node))) throw new FSError(fsErrno.busy);
    if (this.mounts.get(from) !== this.mounts.get(to)) throw new FSError(fsErrno.xdev);
  }

  // Drops each dead node (or just `only`) no name or handle on either side
  // holds; a dropped directory takes what it still holds with it. Nothing is
  // dropped while a batch of the other side's ops applies, or while a
  // statement in flight may still undo this side's recent changes.
  prune(only) {
    if (this.batch || this.undoable || only && !this.dead.has(only)) return;
    for (const [node, size] of only ? [[only, this.dead.get(only)]] : this.dead) {
      if (node.type !== 'dir' && node.nlink > 0) {
        this.dead.delete(node);
      } else if (!this.open.has(node) && !this.remote.has(node)) {
        this.dead.delete(node);
        this.nodes.delete(idOf(node));
        this.resident -= size;
        this.unflushed?.delete(node);
        for (const name in node.type === 'dir' ? node.entries : {}) {
          const child = node.entries[name];
          if (child.type !== 'dir') child.nlink--;
          this.dead.set(child, this.bytes(child));
        }
      }
    }
  }

  fileSize(node) { return this.backend(node).fileSize(node); }

  syncDirectory(dir) { this.backend(dir).syncDirectory(dir); }

  createChild(parent, name, node) {
    this.reap();
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).createChild(parent, name, node);
    // A node named again after losing its name already counts.
    if (!this.dead.delete(node)) this.index(node, this.mounts.get(parent));
    this.note([op.create, idOf(parent), name, idOf(node), node.type, node.target ?? null], restore);
  }

  // A durable mount keeps one name per file, as the OPFS store does.
  linkChild(parent, name, node) {
    this.reap();
    this.check(undefined, parent, node);
    if (this.durable(parent)) throw new FSError(fsErrno.notsup);
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).linkChild(parent, name, node);
    this.note([op.link, idOf(parent), name, idOf(node)], restore);
  }

  removeChild(parent, name) {
    this.reap();
    const node = parent.entries[name], size = this.bytes(node);
    this.check(node, parent);
    const restore = this.saved([[parent, name]], [node]);
    this.backend(parent).removeChild(parent, name);
    this.dead.set(node, size);
    this.unnamed.push(node);
    this.note([op.unlink, idOf(parent), name, idOf(node)], restore);
  }

  renameChild(from, fromName, to, toName) {
    this.reap();
    const node = from.entries[fromName], replaced = to.entries[toName];
    const size = replaced && replaced !== node ? this.bytes(replaced) : 0;
    this.check(node, from, to);
    if (replaced !== node) this.check(replaced, to);
    const restore = this.saved([[from, fromName], [to, toName]], [node, replaced]);
    this.backend(from).renameChild(from, fromName, to, toName);
    if (replaced && replaced !== node) {
      this.dead.set(replaced, size);
      this.unnamed.push(replaced);
    }
    this.note([op.rename, idOf(from), fromName, idOf(to), toName, idOf(node)], restore);
  }

  openFile(node, mode) {
    this.reap();
    const handle = this.backend(node).openFile(node, mode), id = idOf(node), count = this.open.get(node) ?? 0;
    this.open.set(node, count + 1);
    if (!count && this.journal) this.record([op.hold, id]);
    let closed = false;
    return {
      readAt: (buffer, offset) => handle.readAt(buffer, offset),
      writeAt: (data, offset) => {
        const size = this.fileSize(node);
        this.admit(node, offset + data.byteLength - size);
        const written = handle.writeAt(data, offset);
        this.grow(node, Math.max(0, offset + written - size));
        if (written > 0 && this.durable(node)) this.unflushed?.add(node);
        if (this.journal) this.record([op.write, id, offset, data.slice(0, written)]);
        return written;
      },
      resize: size => {
        const before = this.fileSize(node);
        this.admit(node, size - before);
        handle.resize(size);
        this.grow(node, size - before);
        if (this.durable(node)) this.unflushed?.add(node);
        if (this.journal) this.record([op.resize, id, size]);
      },
      sync: () => {
        handle.sync();
        this.unflushed?.delete(node);
        if (this.journal) this.record([op.sync, id]);
      },
      datasync: () => {
        handle.datasync();
        this.unflushed?.delete(node);
        if (this.journal) this.record([op.sync, id]);
      },
      close: () => {
        if (closed) return;
        closed = true;
        if (this.dead.has(node)) this.dead.set(node, this.bytes(node));
        const left = this.open.get(node) - 1;
        if (left) this.open.set(node, left);
        else this.open.delete(node);
        try { handle.close(); }
        finally {
          if (!left && this.journal) this.record([op.release, id]);
          if (!left && this.dead.has(node)) this.prune(node);
        }
      },
    };
  }
}

function materialize([, , , id, type, target]) {
  const now = nowNs(), node = type === 'dir' ? {type, entries: Object.create(null)} :
    type === 'file' ? {type, content: new Uint8Array(0), nlink: 1} :
    type === 'symlink' ? {type, target, nlink: 1} : {type, kind: 'devnull', nlink: 1};
  return Object.assign(node, {ino: BigInt(id), atim: now, mtim: now, ctim: now});
}

function unlink(storage, parent, name, node) {
  storage.removeChild(parent, name);
  delete parent.entries[name];
  if (node.type !== 'dir') node.nlink--;
}

// Applies a recorded op to `storage`'s tree as its syscall changed the tree
// that recorded it. An op that names a node this tree has dropped, or a name
// that no longer holds its node, changes nothing; a sync is the worker's.
function applyOp(storage, entry) {
  const {nodes} = storage, [kind, a, b, c] = entry;
  if (kind === op.create || kind === op.link) {
    // A create names a new node, or one that lost every name (a guest op
    // redone after a statement replaced it); a node still named elsewhere
    // was created already. A link names a known node once more.
    const parent = nodes.get(a), known = nodes.get(c);
    const fresh = !known || storage.dead.has(known) && !(known.nlink > 0);
    const node = kind === op.create ? fresh && (known ?? materialize(entry)) : known;
    if (parent?.type !== 'dir' || !node || parent.entries[b] === node) return;
    if (parent.entries[b]) unlink(storage, parent, b, parent.entries[b]);
    if (kind === op.create) storage.createChild(parent, b, node);
    else storage.linkChild(parent, b, node);
    parent.entries[b] = node;
    if (node.type !== 'dir') node.nlink = kind === op.create ? 1 : node.nlink + 1;
  } else if (kind === op.unlink) {
    const parent = nodes.get(a), node = nodes.get(c);
    if (node && parent?.entries[b] === node) unlink(storage, parent, b, node);
  } else if (kind === op.rename) {
    const [, , , , toName, id] = entry, from = nodes.get(a), to = nodes.get(c), node = nodes.get(id);
    if (!node || to?.type !== 'dir' || from?.entries[b] !== node) return;
    const replaced = to.entries[toName];
    storage.renameChild(from, b, to, toName);
    delete from.entries[b];
    to.entries[toName] = node;
    if (replaced && replaced !== node && replaced.type !== 'dir') replaced.nlink--;
  } else if (kind === op.hold || kind === op.release) {
    // This side's own handle keeps the file's stored bytes while the other
    // side holds it.
    const node = nodes.get(a), held = node && storage.remote.get(node);
    if (kind === op.hold && node?.type === 'file' && !held) {
      storage.remote.set(node, storage.backend(node).openFile(node, {read: true, write: false}));
    } else if (kind === op.release && held) {
      storage.remote.delete(node);
      held.close();
      storage.prune(node);
    }
  } else if (kind !== op.sync && nodes.get(a)?.type === 'file') {
    const handle = storage.openFile(nodes.get(a), {read: false, write: true});
    try {
      if (kind === op.resize && b !== storage.fileSize(nodes.get(a))) handle.resize(b);
      // A short write (a full store) fails the op rather than truncating it.
      for (let at = 0; kind === op.write && at < c.byteLength;) {
        const written = handle.writeAt(c.subarray(at), b + at);
        if (written <= 0) throw new FSError(fsErrno.nospc);
        at += written;
      }
    } finally { handle.close(); }
  }
}
// storage core: end generated

const threads = globalThis.process?.getBuiltinModule?.('node:worker_threads');
const nodeFs = globalThis.process?.getBuiltinModule?.('node:fs');
const port = threads ? threads.parentPort : globalThis;
let queue = Promise.resolve(), fileSystem, storage, limit, service, stores = [], applied = 0, failure;
let next = -1;
const allocateIno = () => BigInt(next += 2);

function describe(cause) {
  return {name: cause?.name ?? 'Error', message: String(cause?.message ?? cause), errno: cause?.errno};
}

function receive(message) {
  queue = queue.then(() => handle(message)).catch(cause => port.postMessage({type: 'fatal', error: describe(cause)}));
}

if (threads) port.on('message', receive);
else port.onmessage = event => receive(event.data);

async function settle() {
  for (const store of stores) await store.settle();
}

// A guest change the mirror could not apply (a full or failing store) leaves
// it behind the guest for good: every later sync, statement and disposal
// reports it.
function attempt(change) {
  try { change(); }
  catch (cause) {
    if (!(cause instanceof FSError)) throw cause;
    failure ??= cause;
  }
}

function reported() {
  if (failure) throw failure;
}

// Durable: OPFS writes reach storage only through a handle flush.
function flush(id) {
  const file = storage.nodes.get(id);
  if (file?.type !== 'file' || !storage.durable(file)) return;
  storage.backend(file).flushHandle(file);
  storage.unflushed.delete(file);
}

async function bytesOf(url) {
  if (nodeFs && !/^(https?|data|blob):/i.test(url)) {
    return new Uint8Array(await nodeFs.promises.readFile(url.startsWith('file:') ? new URL(url) : url));
  }
  const response = await fetch(url, {credentials: 'same-origin'});
  if (!response.ok) throw new Error(`SQLite service request failed (${response.status})`);
  return new Uint8Array(await response.arrayBuffer());
}

// The link recorded the service's digest; other bytes never run.
async function loadService({url, sha256}) {
  const bytes = await bytesOf(url);
  const digest = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))]
    .map(byte => byte.toString(16).padStart(2, '0')).join('');
  if (digest !== sha256) throw new Error(`SQLite service ${url} has digest ${digest}, not the linked ${sha256}`);
  let memory, view;
  const memoryView = () => view?.buffer === memory.buffer ? view : (view = new DataView(memory.buffer));
  const {syscalls} = uwasi.bindFSSyscallsWithController(storage, fileSystem, {}, new uwasi.WASIAbi(), memoryView);
  // The service makes directories only as SQLite's dot-file locks, which
  // order its own connections. They live here, never in the namespace, so a
  // stopped worker leaves none behind and a store's names are all the
  // program's.
  const locks = new Set(), {WASIAbi} = uwasi;
  const lockOf = (fd, at, length) => `${fd}/${new TextDecoder().decode(new Uint8Array(memory.buffer, at, length))}`;
  const instance = await WebAssembly.instantiate(await WebAssembly.compile(bytes), {wasi_snapshot_preview1: {
    ...syscalls,
    path_create_directory(fd, at, length) {
      const lock = lockOf(fd, at, length);
      if (locks.has(lock)) return WASIAbi.WASI_ERRNO_EXIST;
      locks.add(lock);
      return 0;
    },
    path_remove_directory: (fd, at, length) => locks.delete(lockOf(fd, at, length)) ? 0 : WASIAbi.WASI_ERRNO_NOENT,
    path_filestat_get(fd, flags, at, length, out) {
      if (!locks.has(lockOf(fd, at, length))) return syscalls.path_filestat_get(fd, flags, at, length, out);
      new Uint8Array(memory.buffer, out, 64).fill(0);
      memoryView().setUint8(out + 16, WASIAbi.WASI_FILETYPE_DIRECTORY);
      memoryView().setBigUint64(out + 24, 1n, true);
      return 0;
    },
    clock_time_get(id, _precision, out) {
      if (id >>> 0 > 3) return uwasi.WASIAbi.WASI_ERRNO_INVAL;
      memoryView().setBigUint64(out, id === 0 ? BigInt(Date.now()) * 1000000n : BigInt(Math.round(performance.now() * 1e6)), true);
      return 0;
    },
    environ_get: () => 0,
    environ_sizes_get(count, size) {
      memoryView().setUint32(count, 0, true);
      memoryView().setUint32(size, 0, true);
      return 0;
    },
    // A busy timeout cannot block this thread; SQLite reports SQLITE_BUSY.
    poll_oneoff: () => uwasi.WASIAbi.WASI_ENOSYS,
    proc_exit: code => { throw new Error(`SQLite service exited (${code})`); },
  }});
  memory = instance.exports.memory;
  instance.exports._initialize();
  return instance.exports;
}

// A mount's tree as the guest grafts it: its nodes, then their bytes.
function hydration(dir, store, entries = []) {
  for (const name in dir.entries) {
    const node = dir.entries[name];
    entries.push([op.create, idOf(dir), name, idOf(node), node.type, node.target ?? null]);
    if (node.type === 'dir') hydration(node, store, entries);
    if (node.type !== 'file' || !store.fileSize(node)) continue;
    const bytes = new Uint8Array(store.fileSize(node)), handle = store.openFile(node, {read: true, write: false});
    try { handle.readAt(bytes, 0); }
    finally { handle.close(); }
    entries.push([op.write, idOf(node), 0, bytes]);
  }
  return entries;
}

const commands = {
  // The guest's tree, its mounts, and each durable mount's store, hydrated.
  // A failed start releases the stores it opened.
  async init({root, base, mounts, limit: bound, sqlite}) {
    try {
      fileSystem = new uwasi.MemoryFileSystem(undefined, {allocateIno, devices: false});
      fileSystem.lookup('/').ino = BigInt(root);
      storage = new StorageBackend(fileSystem, limit = bound);
      storage.unflushed = new Set();
      for (const entry of base) applyOp(storage, entry);
      const durable = mounts.some(mount => mount.backend === 'opfs');
      const opfs = durable ? await globalThis.navigator?.storage?.getDirectory?.() : undefined;
      if (durable && !opfs) throw new Error('browser durable mounts need the Origin Private File System');
      const hydrated = [];
      for (const {path, backend, directory} of mounts) {
        if (backend === 'memory') {
          storage.mount(fileSystem, path, {root: fileSystem.lookup(path), backend: storage.memory, durable: false});
          continue;
        }
        const store = await uwasi.ExclusiveOPFSBackend.create(await opfs.getDirectoryHandle(directory, {create: true}),
          {namespace: {allocateIno, devices: false}});
        stores.push(store);
        const node = store.fileSystem.lookup('/'), slash = path.lastIndexOf('/');
        fileSystem.lookup(path.slice(0, slash) || '/').entries[path.slice(slash + 1)] = node;
        storage.mount(fileSystem, path, {root: node, backend: store, durable: true});
        if (storage.resident > limit) {
          throw new RangeError(`browser vfs mount ${path} holds more than maxHydratedBytes (${limit})`);
        }
        hydrated.push({path, root: idOf(node), nodes: hydration(node, store)});
      }
      if (sqlite) service = await loadService(sqlite);
      return {mounts: hydrated};
    } catch (cause) {
      for (const store of stores.splice(0)) await store.close().catch(() => {});
      throw cause;
    }
  },

  // The guest's changes in order. A file overdrafted past the spare pool gets
  // its data file in settle(), so the batch's syncs flush after it.
  async ops({ops}) {
    const syncs = [];
    storage.batch = true;
    try {
      for (const entry of ops) {
        if (entry[0] === op.sync) syncs.push(entry[1]);
        else attempt(() => applyOp(storage, entry));
        applied++;
      }
    } finally { storage.batch = false; }
    storage.prune();
    if (syncs.length) await settle();
    for (const id of syncs) attempt(() => flush(id));
    port.postMessage({type: 'ack', seq: applied, unflushed: unflushed()});
  },

  async sync({node}) {
    await settle();
    reported();
    flush(node);
  },

  // One statement, run to completion within the durable `cap` the guest
  // granted it. The spare pool is full first, so files it creates get data
  // files and its syncs flush them.
  async sql({frame, cwd, cap}) {
    reported();
    if (!service) throw new Error('the SQLite service failed');
    await settle();
    enter(typeof cwd === 'string' ? cwd : undefined);
    const deltas = storage.journal = [];
    storage.limit = cap;
    let reply;
    try { reply = serve(frame); }
    finally {
      storage.journal = null;
      storage.limit = limit;
    }
    storage.prune();
    return {frame: reply, deltas};
  },

  async dispose() {
    await settle();
    reported();
    for (const store of stores) await store.persistAll();
    storage.unflushed.clear();
    for (const store of stores.splice(0)) await store.close();
  },
};

// One frame through the service; a trap leaves it unusable.
function serve(frame) {
  const {memory, titan_sql_svc_alloc: alloc, titan_sql_svc_free: free, titan_sql_svc_dispatch: dispatch} = service;
  const pointer = alloc(frame.length);
  if (!pointer) throw new RangeError('SQLite request frame exceeds the service limit');
  try {
    new Uint8Array(memory.buffer).set(frame, pointer);
    const at = dispatch(pointer, frame.length);
    const reply = new Uint8Array(memory.buffer).slice(at + 4, at + 4 + new DataView(memory.buffer).getUint32(at, true));
    free(pointer);
    return reply;
  } catch (cause) {
    service = undefined;
    throw cause;
  }
}

// The service's own CHDIR (op 14), before every frame, so the names SQLite
// resolves itself (ATTACH, VACUUM INTO) are relative to the guest's working
// directory `cwd`; with none given, or one the service cannot enter, every
// relative name fails. A malformed `cwd`, or a CHDIR the service fails (out
// of memory), rejects the request unrun.
function enter(cwd) {
  if (cwd !== undefined && (!cwd.startsWith('/') || cwd.includes('\0'))) {
    throw new TypeError(`titan:sqlite3 working directory ${JSON.stringify(cwd)} is not an absolute path`);
  }
  const path = new TextEncoder().encode(cwd ?? ''), frame = new Uint8Array(20 + path.length);
  frame[0] = 14;
  frame[1] = 1;
  new DataView(frame.buffer).setUint32(16, path.length, true);
  frame.set(path, 20);
  if (serve(frame)[1] !== 0) throw new Error('the SQLite service cannot take the guest\'s working directory');
}

// Whether a forced stop would lose durable writes: a named file holds writes,
// the guest's or SQLite's, that no flush has covered, or a guest change the
// mirror could not apply (which may have failed before any byte landed)
// never reached the store.
function unflushed() {
  if (failure) return true;
  for (const node of storage?.unflushed ?? []) if (node.nlink > 0) return true;
  return false;
}

// A reply moves its frame and the written bytes of its changes.
async function handle(message) {
  if (message.type === 'ops') return commands.ops(message);
  let value;
  try { value = await commands[message.type](message); }
  catch (cause) {
    port.postMessage({type: 'reply', id: message.id, error: describe(cause), unflushed: unflushed()});
    return;
  }
  const transfer = value?.frame ?
    [value.frame.buffer, ...value.deltas.filter(entry => entry[0] === op.write).map(entry => entry[3].buffer)] : [];
  port.postMessage({type: 'reply', id: message.id, value, unflushed: unflushed()}, transfer);
}
