        write_file(lua, string.format(wrapper,
            quote('package.cpath = "/usr/lib/lua/5.5/?.so"')))
        checked_run({ "chmod", "+x", lua })
        assert.equal(prefix_output("/usr/local"), inspect(tools_path))
