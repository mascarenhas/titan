            copy_tree(STDLIB_SHIMDIR .. "/" .. module .. ".lua",
                stage .. "/titan/" .. module .. ".lua")
        end
        if lfs.symlinkattributes(STDLIB_PROVIDER .. ".dSYM") then
            copy_tree(STDLIB_PROVIDER .. ".dSYM",
                stage .. "/titan.so.dSYM")
        end
        local install = {
            "make", "--no-print-directory", "-s",
            "PREFIX=" .. PREFIX,
            "ROCKS_TREE=",
            "TITAN_INSTALL_TREE=" .. workspace,
            "TITAN_LUA=" .. LUA,
