#!/usr/bin/env bash

# Remove compiler-generated test artifacts without consulting Git. Below spec/,
# a primary translation unit is removed only when a same-stem Titan source
# exists, so author-written native C fixtures survive. Split-module outputs are
# removed, below spec/ and at the repository root, only through a `.parts`
# companion that exactly matches the compiler's inventory. A Titan-backed stem
# below spec/ without a companion loses only digit-numbered part sources and
# objects and a private header that starts with the compiler's marker.
# Synthetic --test outputs use reserved __test_* suffixes, and root test-runner
# fixtures use the reserved test_runner_* namespace.

set -euo pipefail

keep_output=false
if [[ ${1-} == --keep-output ]]; then
    keep_output=true
    shift
fi
if [[ $# -ne 0 ]]; then
    echo "usage: $0 [--keep-output]" >&2
    exit 2
fi

# In-memory coder fixtures have no same-stem .titan source. A complete,
# compiler-derived companion identifies their outputs without a per-test list.
# Validate the entire inventory before deleting anything; never follow paths
# supplied by a malformed or authored companion.
clean_module_parts() {
    local companion=$1 stem=${1%.parts} leaf=${1##*/}
    leaf=${leaf%.parts}
    local lines=() line='' count offset length index part suffix
    local outputs=("$companion")
    while IFS= read -r line; do
        lines+=("$line")
    done < "$companion"
    [[ -z $line ]] || return 0
    [[ -n ${lines[0]-} ]] || return 0
    length=${#lines[@]}
    if [[ ${lines[0]} == 'titan-parts-v1 1' ]]; then
        [[ $length == 3 ]] || return 0
        count=1
        offset=1
    else
        (( length >= 6 )) || return 0
        count=$(( (length - 2) / 2 ))
        (( length == 2 + 2 * count )) || return 0
        [[ ${lines[0]} == "titan-parts-v1 $count" &&
           ${lines[1]} == "$leaf.priv.h" ]] || return 0
        outputs+=("$stem.priv.h")
        offset=2
    fi
    for ((part=0; part<count; part++)); do
        suffix=''
        if (( part > 0 )); then suffix=.part$part; fi
        index=$((offset + 2 * part))
        [[ ${lines[index]} == "$leaf$suffix.c" &&
           ${lines[index+1]} == "$leaf$suffix.o" ]] || return 0
        outputs+=("$stem$suffix.c" "$stem$suffix.o")
    done
    rm -f -- "${outputs[@]}"
}

# A failed split compile removes its companion and objects but keeps the part
# sources and private header it already wrote. For a Titan-backed stem without
# a companion, remove only names the compiler produces: `.part<k>.c`/`.o` with
# k a positive decimal number, and a `.priv.h` whose first line is the
# compiler's private-header marker. Authored names such as `<stem>.partial.c`
# and unmarked headers survive.
private_header_marker='/* Generated by Titan: module private declarations. */'
clean_orphan_parts() {
    local stem=$1 path number first_line=''
    if [[ -e $stem.parts || -L $stem.parts ]]; then return 0; fi
    for path in "$stem".part*.c "$stem".part*.o; do
        number=${path#"$stem".part}
        number=${number%.[co]}
        if [[ -f $path && $number == [1-9]* && $number != *[!0-9]* ]]; then
            rm -f -- "$path"
        fi
    done
    if [[ -f $stem.priv.h ]]; then
        IFS= read -r first_line < "$stem.priv.h" || true
        if [[ $first_line == "$private_header_marker" ]]; then
            rm -f -- "$stem.priv.h"
        fi
    fi
}

while IFS= read -r -d '' source; do
    if [[ -f ${source%.c}.titan ]]; then rm -f -- "$source"; fi
done < <(find spec -type f -name '*.c' -print0)

while IFS= read -r -d '' titan_source; do
    clean_orphan_parts "${titan_source%.titan}"
done < <(find spec -type f -name '*.titan' -print0)

find spec -type f -name '*.o' -delete

# Generated source-collaboration headers occur below spec/. Prove ownership
# by the exact compiler banner before deletion.
# Root coder helpers own only the exact test.titan.h and test.ffi.h paths.
foreign_header_banner='/* Generated by Titan: source foreign function interface. */'
ffi_header_banner='/* Generated by Titan: module C declaration environment. */'
is_generated_header() {
    local first_line=''
    IFS= read -r first_line < "$1" || true
    [[ $first_line == "$foreign_header_banner" || $first_line == "$ffi_header_banner" ]]
}
while IFS= read -r -d '' header; do
    if is_generated_header "$header"; then rm -f -- "$header"; fi
done < <(
    find spec -type f \( -name '*.titan.h' -o -name '*.ffi.h' \) -print0
    for header in ./test.titan.h ./test.ffi.h; do
        if [[ -f $header ]]; then printf '%s\0' "$header"; fi
    done
)

# A test program's executable and dSYM share the prefix of its reserved
# synthetic support/runner/entrypoint files. Record those prefixes before
# deleting the synthetic files so nested outputs are cleaned without naming
# individual tests here.
test_programs=()
while IFS= read -r -d '' artifact; do
    case $artifact in
        *.ffi.h|*.titan.h)
            if ! is_generated_header "$artifact"; then continue; fi ;;
    esac
    case $artifact in
        *__test_support.*) program=${artifact%__test_support.*} ;;
        *__test_runner.*) program=${artifact%__test_runner.*} ;;
        *__test_entrypoint.*) program=${artifact%__test_entrypoint.*} ;;
        *) continue ;;
    esac
    test_programs+=("$program")
    rm -f -- "$artifact"
done < <(find . \
    -path './.git' -prune -o \
    -path './.lua' -prune -o \
    -path './.titan-tests' -prune -o \
    -path './out' -prune -o \
    -type f \( \
        -name '*__test_support.titan' -o \
        -name '*__test_support.c' -o -name '*__test_support.o' -o \
        -name '*__test_support.parts' -o -name '*__test_support.priv.h' -o \
        -name '*__test_support.part*.c' -o -name '*__test_support.part*.o' -o \
        -name '*__test_support.ffi.h' -o -name '*__test_support.titan.h' -o \
        -name '*__test_runner.titan' -o \
        -name '*__test_runner.c' -o -name '*__test_runner.o' -o \
        -name '*__test_runner.parts' -o -name '*__test_runner.priv.h' -o \
        -name '*__test_runner.part*.c' -o -name '*__test_runner.part*.o' -o \
        -name '*__test_runner.ffi.h' -o -name '*__test_runner.titan.h' -o \
        -name '*__test_entrypoint.titan' -o \
        -name '*__test_entrypoint.c' -o -name '*__test_entrypoint.o' -o \
        -name '*__test_entrypoint.parts' -o -name '*__test_entrypoint.priv.h' -o \
        -name '*__test_entrypoint.part*.c' -o -name '*__test_entrypoint.part*.o' -o \
        -name '*__test_entrypoint.ffi.h' -o -name '*__test_entrypoint.titan.h' \
    \) -print0)

# Bash 3.2 treats a declared empty array as unset under nounset. The + form
# expands to no arguments when the array is empty while preserving each value.
for program in "${test_programs[@]+"${test_programs[@]}"}"; do
    rm -f -- "$program"
    rm -rf -- "$program.dSYM"
    parent=${program%/*}
    while [[ $parent != "$program" && $parent != . && $parent != / ]]; do
        rmdir -- "$parent" 2>/dev/null || break
        program=$parent
        parent=${program%/*}
    done
done

# Root-level files and directories with this prefix are owned exclusively by
# the test-runner compiler specs, including interrupted collision fixtures.
for fixture in ./test_runner_*; do
    if [[ -e $fixture || -L $fixture ]]; then rm -rf -- "$fixture"; fi
done

while IFS= read -r -d '' companion; do
    clean_module_parts "$companion"
done < <(
    find spec -type f -name '*.parts' -print0
    for companion in ./*.parts; do
        if [[ -f $companion ]]; then printf '%s\0' "$companion"; fi
    done
)

if ! $keep_output; then rm -rf -- .titan-tests out/tests; fi
