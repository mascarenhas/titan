#!/usr/bin/env bash

# Remove compiler-generated test artifacts without consulting Git. Translation
# units below spec/ are generated only when a same-stem Titan source exists;
# author-written native C fixtures therefore survive. Synthetic --test outputs
# use reserved __test_* suffixes, and root test-runner fixtures use the reserved
# test_runner_* namespace.

set -euo pipefail

keep_output=false
if [[ ${1-} == --keep-output ]]; then
    keep_output=true
    shift
fi
if [[ $# -ne 0 ]]; then
    echo "usage: $0 [--keep-output]" >&2
    exit 2
fi

while IFS= read -r -d '' source; do
    if [[ -f ${source%.c}.titan ]]; then rm -f -- "$source"; fi
done < <(find spec -type f -name '*.c' -print0)

find spec -type f -name '*.o' -delete

# Generated source-collaboration headers also occur in example and compiler
# test sources. Prove ownership by the exact compiler banner before deletion.
# Root coder helpers own only the exact test.titan.h and test.ffi.h paths.
foreign_header_banner='/* Generated by Titan: source foreign function interface. */'
ffi_header_banner='/* Generated by Titan: module C declaration environment. */'
is_generated_header() {
    local first_line=''
    IFS= read -r first_line < "$1" || true
    [[ $first_line == "$foreign_header_banner" || $first_line == "$ffi_header_banner" ]]
}
while IFS= read -r -d '' header; do
    if is_generated_header "$header"; then rm -f -- "$header"; fi
done < <(
    for directory in spec examples testfiles; do
        if [[ -d $directory ]]; then
            find "$directory" -type f \( -name '*.titan.h' -o -name '*.ffi.h' \) -print0
        fi
    done
    for header in ./test.titan.h ./test.ffi.h; do
        if [[ -f $header ]]; then printf '%s\0' "$header"; fi
    done
)

# A test program's executable and dSYM share the prefix of its reserved
# synthetic support/runner/entrypoint files. Record those prefixes before
# deleting the synthetic files so nested outputs are cleaned without naming
# individual tests here.
test_programs=()
while IFS= read -r -d '' artifact; do
    case $artifact in
        *.ffi.h|*.titan.h)
            if ! is_generated_header "$artifact"; then continue; fi ;;
    esac
    case $artifact in
        *__test_support.*) program=${artifact%__test_support.*} ;;
        *__test_runner.*) program=${artifact%__test_runner.*} ;;
        *__test_entrypoint.*) program=${artifact%__test_entrypoint.*} ;;
        *) continue ;;
    esac
    test_programs+=("$program")
    rm -f -- "$artifact"
done < <(find . \
    -path './.git' -prune -o \
    -path './.lua' -prune -o \
    -path './.titan-tests' -prune -o \
    -path './out' -prune -o \
    -type f \( \
        -name '*__test_support.titan' -o \
        -name '*__test_support.c' -o -name '*__test_support.o' -o \
        -name '*__test_support.ffi.h' -o -name '*__test_support.titan.h' -o \
        -name '*__test_runner.titan' -o \
        -name '*__test_runner.c' -o -name '*__test_runner.o' -o \
        -name '*__test_runner.ffi.h' -o -name '*__test_runner.titan.h' -o \
        -name '*__test_entrypoint.titan' -o \
        -name '*__test_entrypoint.c' -o -name '*__test_entrypoint.o' -o \
        -name '*__test_entrypoint.ffi.h' -o -name '*__test_entrypoint.titan.h' \
    \) -print0)

# Bash 3.2 treats a declared empty array as unset under nounset. The + form
# expands to no arguments when the array is empty while preserving each value.
for program in "${test_programs[@]+"${test_programs[@]}"}"; do
    rm -f -- "$program"
    rm -rf -- "$program.dSYM"
    parent=${program%/*}
    while [[ $parent != "$program" && $parent != . && $parent != / ]]; do
        rmdir -- "$parent" 2>/dev/null || break
        program=$parent
        parent=${program%/*}
    done
done

# Root-level files and directories with this prefix are owned exclusively by
# the test-runner compiler specs, including interrupted collision fixtures.
for fixture in ./test_runner_*; do
    if [[ -e $fixture || -L $fixture ]]; then rm -rf -- "$fixture"; fi
done

if ! $keep_output; then rm -rf -- .titan-tests out/tests; fi
