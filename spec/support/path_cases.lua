-- Shared lexical path expectations for the Lua compiler helper and Titan
-- standard module. Each result is a list because split returns two strings.
-- Go filepath's published edge cases inform the native Windows root cases.
local cases = {}
local function add(operation, arguments, posix, windows)
    cases[#cases + 1] = {
        operation = operation, arguments = arguments,
        posix = type(posix) == "table" and posix or { posix },
        windows = type(windows) == "table" and windows or { windows },
    }
end

