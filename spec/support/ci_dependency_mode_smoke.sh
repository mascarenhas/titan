#!/usr/bin/env bash

# Exercise both installed standard-library provider forms under the bundled
# and system OpenSSL policies. Libuv, llhttp and SQLite are always bundled.
# Besides the ordinary Lua/API smokes, this proves titan.a matches titan.so and
# can load io and run
# async/timer/fs/net/ssl/url/http/websocket/os plus PEG/string behavior in a compiled Titan
# application while the dynamic provider and generated shims are out of search
# reach. System mode exercises the host's ordinary OpenSSL pkg-config settings.

set -euo pipefail

scope=${1:-both}
case "$scope" in
    bundled|system|both) ;;
    *)
        echo "usage: $0 [bundled|system|both]" >&2
        exit 2
        ;;
esac

PREFIX="${PREFIX:-$PWD/.lua}"
if [[ $PREFIX != /* ]]; then PREFIX=$PWD/$PREFIX; fi
PREFIX=$(CDPATH= cd "$PREFIX" && pwd -P)
LUA="$PREFIX/bin/lua"
TITANC="$PREFIX/bin/titanc"
LIBRARY_ROOT="$PREFIX/lib/titan/0.6"
SHIM_ROOT="$PREFIX/share/lua/5.5"
PROVIDER="$LIBRARY_ROOT/titan.so"
STATIC_ARCHIVE="$LIBRARY_ROOT/titan.a"
RUNTIME_ARCHIVE="$LIBRARY_ROOT/libtitan.a"
TEST_SUPPORT_SOURCE="$PREFIX/share/titan/0.6/src/titan/test.titan"
PROCESS_CHILD_SUPPLIED=${TITAN_PROCESS_SMOKE_CHILD:+1}
OPENSSL_PKG_CONFIG=${OPENSSL_PKG_CONFIG:-pkg-config}
OPENSSL_MODE=${OPENSSL_MODE:-bundled}

case "$OPENSSL_MODE" in
    bundled|system) ;;
    *)
        echo "OPENSSL_MODE must be bundled or system, not '$OPENSSL_MODE'" >&2
        exit 2
        ;;
esac

test -x "$LUA"
test -x "$TITANC"

case "$(uname -s)" in
    Darwin)
        platform=macos
        openssl_pkgconfig="$(brew --prefix openssl@3)/lib/pkgconfig"
        export PKG_CONFIG_PATH="$openssl_pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
        bundled_cppflags="-I$PREFIX/include"
        bundled_ldflags="-lpthread"
        ;;
    Linux)
        platform=linux
        bundled_cppflags="-I$PREFIX/include -D_GNU_SOURCE"
        bundled_ldflags="-lpthread -lrt"
        ;;
    *)
        echo "unsupported dependency smoke platform: $(uname -s)" >&2
        exit 2
        ;;
esac

SMOKE_TMP=$(mktemp -d "${TMPDIR:-/tmp}/titan-dependency-mode-smoke.XXXXXX")
PROVIDER_HIDDEN="$LIBRARY_ROOT/.titan.so.libuv-smoke-hidden.$$"
SHIMS_HIDDEN="$SHIM_ROOT/.titan.libuv-smoke-hidden.$$"

restore_hidden_provider() {
    if [[ -e $PROVIDER_HIDDEN || -L $PROVIDER_HIDDEN ]]; then
        mv "$PROVIDER_HIDDEN" "$PROVIDER"
    fi
    if [[ -e $SHIMS_HIDDEN || -L $SHIMS_HIDDEN ]]; then
        mv "$SHIMS_HIDDEN" "$SHIM_ROOT/titan"
    fi
}

cleanup() {
    restore_hidden_provider
    rm -rf "$SMOKE_TMP"
}
trap cleanup EXIT HUP INT TERM

check_canonical_container() {
    local module

    test -f "$PROVIDER"
    test ! -L "$PROVIDER"
    test -f "$STATIC_ARCHIVE"
    test ! -L "$STATIC_ARCHIVE"
    test -f "$RUNTIME_ARCHIVE"
    test ! -L "$RUNTIME_ARCHIVE"
    test ! -e "$PREFIX/lib/libtitan.a"
    test ! -e "$PREFIX/lib/libuv.a"
    test -s "$TEST_SUPPORT_SOURCE"
    test ! -L "$TEST_SUPPORT_SOURCE"
    grep -Fq 'function testing(): boolean' "$TEST_SUPPORT_SOURCE"
    test ! -e "$PROVIDER.dSYM" || [[ $platform == macos ]]
    if [[ $platform == macos ]]; then
        test -d "$PROVIDER.dSYM"
        test -f "$PROVIDER.dSYM/Contents/Resources/DWARF/titan.so"
    fi

    for module in coroutine uv async timer io fs net ssl url http websocket os peg string math lua iteration gc test reflect sqlite3 json; do
        local shim="$SHIM_ROOT/titan/$module.lua"

        test -f "$shim"
        test ! -L "$shim"
        grep -Fqx -- '-- Generated by titanc; do not edit.' \
            < <(head -n 1 "$shim")
        grep -Fq 'package.searchpath("titan", package.cpath)' "$shim"
        grep -Fq "luaopen_titan_$module" "$shim"
        test ! -e "$LIBRARY_ROOT/titan/$module.so"
        test ! -e "$LIBRARY_ROOT/titan/$module.so.dSYM"
        test ! -e "$LIBRARY_ROOT/$module.so"
        test ! -e "$LIBRARY_ROOT/$module.so.dSYM"
        test ! -e "$PREFIX/lib/lua/5.5/titan/$module.so"
        test ! -e "$PREFIX/lib/lua/5.5/titan/$module.so.dSYM"
    done
    test ! -e "$PREFIX/lib/lua/5.5/titan.so"
    test ! -e "$PREFIX/lib/lua/5.5/titan.so.dSYM"
}

compare_archive_and_dso_metadata() {
    local archive=${1:-$STATIC_ARCHIVE}
    local dso=${2:-$PROVIDER}
    TITAN_ROCKS_ROOT="$PREFIX" "$LUA" -E - \
        "$archive" "$dso" <<'LUA'
local archive, dso = ...
local driver = require "titan-compiler.driver"
local metadata = require "titan-compiler.staticmetadata"
local expected = {
    ["titan.coroutine"] = true,
    ["titan.uv"] = true,
    ["titan.async"] = true,
    ["titan.timer"] = true,
    ["titan.io"] = true,
    ["titan.fs"] = true,
    ["titan.net"] = true,
    ["titan.ssl"] = true,
    ["titan.url"] = true,
    ["titan.http"] = true,
    ["titan.websocket"] = true,
    ["titan.os"] = true,
    ["titan.peg"] = true,
    ["titan.string"] = true,
    ["titan.math"] = true,
    ["titan.lua"] = true,
    ["titan.iteration"] = true,
    ["titan.gc"] = true,
    ["titan.test"] = true,
    ["titan.reflect"] = true,
    ["titan.sqlite3"] = true,
    ["titan.json"] = true,
}

local scanned, scan_error = metadata.scan_archive(archive, {
    expected_abi = driver.TITAN_ABI_VERSION,
    validate_types = function(name, serialized, origin)
        return driver.decode_module_interface(serialized, name, origin)
    end,
})
assert(scanned, scan_error)
for name in pairs(scanned.entries) do
    assert(expected[name], "unexpected installed titan.a key " .. name)
    expected[name] = nil
end
assert(next(expected) == nil,
    "installed titan.a is missing key " .. tostring(next(expected)))

local support_open, support_error = package.loadlib(dso, "luaopen_titan")
assert(support_open, support_error)
local support = support_open()
assert(type(support) == "table" and type(support._loadlib) == "function" and
    type(support._loadlibglobal) == "function")
for name, embedded in pairs(scanned.entries) do
    local prefix = name:gsub("[%-.]", "_")
    local abi = assert(support._loadlib(dso, prefix .. "_abi"))
    local types = assert(support._loadlib(dso, prefix .. "_types"))
    local abi_values = table.pack(pcall(abi))
    local type_values = table.pack(pcall(types))
    assert(abi_values[1] and abi_values.n == 2 and
        abi_values[2] == embedded.abi,
        name .. " ABI differs between titan.a and titan.so")
    assert(type_values[1] and type_values.n == 2 and
        type_values[2] == embedded.types,
        name .. " types differ between titan.a and titan.so")
    assert(support._loadlib(dso, prefix .. "_init"))
    assert(support._loadlib(dso, "luaopen_" .. prefix))
end
LUA
}

inspect_dependencies() {
    if [[ $platform == macos ]]; then
        # `otool -L` mixes actual loads with filename/architecture headers and
        # a shared library's own LC_ID_DYLIB. Parse the load commands so a
        # staged output pathname is never mistaken for one of its dependencies.
        otool -l "$1" | awk '
            $1 == "cmd" {
                dependency = ($2 ~ /^LC_.*DYLIB$/ &&
                    $2 != "LC_ID_DYLIB")
                next
            }
            dependency && $1 == "name" {
                print
                dependency = 0
            }
        '
    else
        readelf -d "$1"
    fi
}

has_libuv_dependency() {
    inspect_dependencies "$1" | grep -qi libuv
}

has_openssl_dependency() {
    inspect_dependencies "$1" | grep -Eqi 'lib(ssl|crypto)'
}

has_lpeglabel_dependency() {
    inspect_dependencies "$1" | grep -qi lpeglabel
}

dynamic_symbols() {
    if [[ $platform == macos ]]; then
        nm -gU "$1"
    else
        nm -D -g "$1"
    fi
}

has_public_lpeglabel_symbol() {
    dynamic_symbols "$1" | awk '
        {
            symbol = $NF
            sub(/^_/, "", symbol)
            if (symbol == "luaopen_lpeglabel" ||
                    symbol ~ /^titan_lpeglabel_/) found = 1
        }
        END { exit(found ? 0 : 1) }
    '
}

has_unprefixed_lpeglabel_definition() {
    nm -g "$1" | awk '
        {
            if (NF < 2) next
            symbol = $NF
            type = $(NF - 1)
            sub(/^_/, "", symbol)
            if (type == "U" || type == "u") next
            if (symbol ~ /^(finddyncap|getcaptures|runtimecap|checkaux|compile|fixedlen|hascaptures|realloccode|sizei|tocharset|lp_gc|numsiblings|match|printcaplist|printcharset|printinst|printktable|printpatt|printtree|luaopen_lpeglabel)$/) {
                found = 1
            }
        }
        END { exit(found ? 0 : 1) }
    '
}

require_no_titan_dependency() {
    if inspect_dependencies "$1" | grep -qi 'titan[.]so'; then
        echo "static Titan executable unexpectedly depends on titan.so" >&2
        exit 1
    fi
}

require_no_lpeglabel_dependency() {
    if has_lpeglabel_dependency "$1"; then
        echo "Titan image unexpectedly depends on an LPegLabel DSO" >&2
        exit 1
    fi
}

require_no_sqlite3_dependency() {
    if inspect_dependencies "$1" | grep -qi libsqlite3; then
        echo "Titan image unexpectedly depends on a SQLite DSO" >&2
        exit 1
    fi
}

defines_uv_version() {
    nm -g "$1" | awk '
        {
            if (NF < 2) next
            symbol = $NF
            type = $(NF - 1)
            if ((symbol == "uv_version" || symbol == "_uv_version") &&
                type != "U") found = 1
        }
        END { exit(found ? 0 : 1) }
    '
}

defines_ssl_do_handshake() {
    nm -g "$1" | awk '
        {
            if (NF < 2) next
            symbol = $NF
            type = $(NF - 1)
            if ((symbol == "SSL_do_handshake" ||
                    symbol == "_SSL_do_handshake") &&
                type != "U" && type != "u") found = 1
        }
        END { exit(found ? 0 : 1) }
    '
}

system_openssl_flags() {
    system_openssl_cppflags=$(
        "$OPENSSL_PKG_CONFIG" --cflags openssl
    )
    system_openssl_ldflags=$(
        "$OPENSSL_PKG_CONFIG" --libs openssl
    )
}

build_process_child() {
    local mode=$1
    if [[ -n $PROCESS_CHILD_SUPPLIED ]]; then return; fi

    local cc_words cpp_words ld_words
    read -r -a cc_words <<<"${CC:-cc}"
    cpp_words=("-I$PREFIX/include")
    ld_words=("$STATIC_ARCHIVE" "-lpthread")
    if [[ $platform == linux ]]; then
        cpp_words+=("-D_GNU_SOURCE")
        ld_words+=("-lrt" "-ldl" "-lm")
    fi

    # CI uses a single compiler executable (cc/clang). Word splitting also
    # supports the common "ccache cc" configured form and pkg-config output.
    TITAN_PROCESS_SMOKE_CHILD="$SMOKE_TMP/process-child-$mode"
    CCACHE_DISABLE=1 "${cc_words[@]}" \
        -std=c99 -O2 -Wall -Wextra -Werror \
        "${cpp_words[@]}" \
        spec/fixtures/stdlib/native/os_process_child.c \
        "${ld_words[@]}" -o "$TITAN_PROCESS_SMOKE_CHILD"
    export TITAN_PROCESS_SMOKE_CHILD
}

run_mode_smoke() {
    local mode=$1
    local titan_path="$LIBRARY_ROOT"
    local lua_path="$SHIM_ROOT/?.lua;$SHIM_ROOT/?/init.lua"
    local lua_cpath="$LIBRARY_ROOT/?.so"

    env -u LUA_PATH_5_5 -u LUA_CPATH_5_5 \
        TITAN_PATH_0_6="$titan_path" LUA_PATH="$lua_path" \
        LUA_CPATH="$lua_cpath" \
        "$LUA" spec/fixtures/libuv/stdlib_provider_smoke.lua "$mode"

    env -u LUA_PATH_5_5 -u LUA_CPATH_5_5 \
        TITAN_PATH_0_6="$titan_path" LUA_PATH="$lua_path" \
        LUA_CPATH="$lua_cpath" \
        "$LUA" spec/fixtures/libuv/net_production_smoke.lua "$mode"
    # The os facade intentionally supports only pipe and TTY parent streams;
    # CI and noninteractive shells may otherwise supply a regular-file stdin.
    printf '' | env -u LUA_PATH_5_5 -u LUA_CPATH_5_5 \
        TITAN_PATH_0_6="$titan_path" LUA_PATH="$lua_path" \
        LUA_CPATH="$lua_cpath" \
        "$LUA" spec/fixtures/libuv/os_production_smoke.lua "$mode" \
        "$TITAN_PROCESS_SMOKE_CHILD"
}

build_and_run_static_titan() {
    local mode=$1
    local mode_dir="$SMOKE_TMP/static-$mode"
    local executable="$mode_dir/static_uv_smoke"
    local marker="$mode_dir/static-marker"
    local cppflags ldflags
    mkdir -p "$mode_dir"
    cat >"$mode_dir/static_uv_smoke.titan" <<'TITAN'
local async = import "async"
local timer = import "timer"
local titan_io = import "io"
local fs = import "fs"
local net = import "net"
local ssl = import "ssl"
local url = import "url"
local http = import "http"
local websocket = import "websocket"
local qualified_websocket = import "titan.websocket"
local system = import "os"
local peg = import "peg"
local strings = import "string"
local math = import "math"
local lua = import "lua"
local iteration = import "iteration"
local gc = import "gc"
local testing = import "test"
local sqlite3 = import "sqlite3"
local json = import "json"
local reflect = import "reflect"

local function check(condition: boolean, message: string)
  if not condition then raise message end
end

local function active(task: async.Task): boolean
  local status = task:status():as_string()
  return status == "ready" or status == "running" or status == "waiting"
end

local function check_parent_stream(query: function (): (boolean))
  local tty = query()
  check(tty or not tty, "static parent stdio query failed")
end

record JsonSmokeRecord
  const answer: integer
end

union JsonSmokeMessage
  ready(JsonSmokeRecord)
end

local function check_json_provider()
  local input = JsonSmokeMessage.ready(JsonSmokeRecord.new(42))
  local encoded = json.encode(input)
  check(encoded == [[{"tag":"ready","value":{"answer":42}}]],
        "static JSON union encoding failed")
  local descriptor = reflect.Type.is_named(
    reflect.NamedType.new("static_uv_smoke.JsonSmokeMessage"))
  local decoded: JsonSmokeMessage = json.decode(encoded, descriptor)
  check(json.encode(decoded) == encoded,
        "static JSON reflected constructor decoding failed")
  local values: {value} = json.decode("[1,null,3]")
  check(#values == 3 and values[2] == nil,
        "static JSON array hole decoding failed")
end

local function check_sqlite_provider()
  local database = sqlite3.connect(":memory:")
  defer database:close()
  local statement = database:prepare(
    "SELECT ?1 AS answer, ?2 AS payload, NULL AS empty")
  defer statement:close()
  local cursor = statement:query(42, sqlite3.Blob.new("sqlite\0payload"))
  defer cursor:close()
  local row: sqlite3.Row = cursor:fetch()
  check(cursor:fetch() == nil, "static SQLite cursor did not exhaust")
  cursor:close()
  statement:close()
  database:close()
  local answer: integer = row:get(1)
  local blob: sqlite3.Blob = row:get(2)
  check(#row.columns == 3 and answer == 42 and
        blob.bytes == "sqlite\0payload" and row:get(3) == nil,
        "static SQLite provider changed owned row values")
end

local function listen_available(): (net.Server, integer)
  local port = 20000 + system.pid() % 30000
  local attempts = 0
  while attempts < 1024 do
    do
      return net.listen("127.0.0.1", port, 8), port
    catch
      local failure = error as async.OperationError
      if failure.name ~= "EADDRINUSE" then raise error end
    end
    attempts = attempts + 1
    port = port + 1
    if port > 60999 then port = 20000 end
  end
  raise "could not find an available static-smoke loopback port"
end

function main(args: {string}): integer
  local marker = args[1]
  local process_child = args[2]
  check(not testing.testing() and not testing.verbose(),
        "titan.test reported an active runner in a production executable")
  local envname = "TITAN_STATIC_PROVIDER_SMOKE"
  local original: string? = system.getenv(envname)
  defer
    if original then
      system.setenv(envname, original as string)
    else
      system.unsetenv(envname)
    end
  do
    system.setenv(envname, "os-ready")
    check(system.getenv(envname) == "os-ready",
          "static os environment behavior failed")
    check(system.pid() > 0 and #system.cwd() > 0 and
          #system.exepath() > 0,
          "static os identity behavior failed")
    check_json_provider()
    check(#peg.version() > 0,
          "static PEG native engine initialization failed")
    check(strings.len("static\0string") == 13,
          "static string byte behavior failed")
    local found = strings.match("static42", "([0-9]+)")
    check(found and
          found:group(1) == "42",
          "static regex provider behavior failed")
    local literal_first, literal_last =
      strings.find("static\0string", "\0str")
    check(literal_first == 7 and literal_last == 10,
          "static literal string search failed")
    check(math.sqrt(81.0) == 9.0 and
          (math.tonumber("0xff") as integer) == 255,
          "static math provider behavior failed")
    local loaded: value =
      lua.load("return 42", "=static-smoke", nil)()
    check(loaded is integer and (loaded as integer) == 42,
          "static Lua loader provider behavior failed")
    local values: {string: integer} = {
      ["left"] = 20,
      ["right"] = 22,
    }
    local total = 0
    for _key: string, item: integer in iteration.pairs(values) do
      total = total + item
    end
    check(total == 42, "static iterator provider behavior failed")
    gc.pause()
    check(gc.paused(), "static GC pause query failed")
    gc.resume()
    check(not gc.paused() and gc.count() > 0,
          "static GC resume or count behavior failed")
    check_sqlite_provider()

    local dial_options: value = websocket.DialOptions()
    local accept_options: value = qualified_websocket.AcceptOptions()
    check(dial_options is websocket.DialOptions and
          accept_options is websocket.AcceptOptions and
          websocket.TEXT:has_text() and websocket.BINARY:has_binary(),
          "static WebSocket provider initialization failed")
    local websocket_url?, websocket_url_error? = url.parse("wss://localhost/socket")
    check(websocket_url_error == nil and websocket_url.scheme == "wss" and
          websocket_url.port == 443, "static WSS URL parsing failed")

    local tls_error = ssl.Error.new(
      0, "STATIC_SSL_READY", "static SSL module loaded", "static-smoke")
    check(tls_error.name == "STATIC_SSL_READY",
          "static SSL provider initialization failed")
    local parsed?, parse_error? =
      url.parse("https://localhost:8443/static?q=1")
    check(parse_error == nil and parsed ~= nil,
          "static URL provider initialization failed")
    local parsed_url = parsed as url.Url
    check(parsed_url.scheme == "https" and parsed_url.host == "localhost" and
          parsed_url.port == 8443 and parsed_url.target == "/static?q=1",
          "static URL provider parsing failed")

    local server, port = listen_available()
    local peer_result = "not-run"
    local peer = async.run<|value, value|>(function (): value
      local connection = server:accept()
      check(connection:read_until("\n") == "ping\n",
            "static net peer received the wrong payload")
      connection:write("pong\n")
      connection:shutdown()
      connection:close()
      peer_result = "peer-ready"
      return nil
    end)

    local connection = net.connect("127.0.0.1", port)
    connection:write("ping\n")
    connection:shutdown()
    check(connection:read_until("\n") == "pong\n",
          "static net client received the wrong payload")
    connection:close()
    while active(peer) do timer.yield() end
    check(peer:status():as_string() == "succeeded" and peer_result == "peer-ready",
          "static async peer Task failed")
    server:close()

    timer.sleep(0)
    fs.write_file(marker, "static-titan-libuv")
    check(fs.read_file(marker) == "static-titan-libuv",
          "static fs round trip changed the payload")
    local metadata = fs.stat(marker)
    check(metadata.kind == "file" and metadata.size == 18,
          "static fs stat changed size or file classification")

    check_parent_stream(
      function (): boolean return system.stdin:is_tty() end)
    check_parent_stream(
      function (): boolean return system.stdout:is_tty() end)
    check_parent_stream(
      function (): boolean return system.stderr:is_tty() end)

    local merged = titan_io.popen(
      "printf 'static-process-stdout'; " ..
      "printf 'static-process-stderr' >&2")
    local merged_output = ""
    for chunk in merged:read do
      merged_output = merged_output .. chunk
    end
    local merged_status = merged:wait()
    check(merged_output ==
          "static-process-stdoutstatic-process-stderr" and
          merged_status.code == 0 and not merged_status.signal and
          merged_status.signal_number == 0,
          "static io.popen changed merged output or exit status")
    merged:close()

    local process_args: {string} = {"echo"}
    local process_payload = "static\0process\0payload"
    local process = system.spawn(
      process_child, process_args,
      system.with_stdin, system.with_stdout, system.with_stderr)
    local process_input? = process.stdin
    local process_output? = process.stdout
    local process_diagnostics? = process.stderr
    check(process_input and process_output and process_diagnostics,
          "static captured process omitted a standard stream")
    local writer: titan_io.WriterCloser =
      process_input as system.OutputStream
    local reader: titan_io.Reader = process_output as system.InputStream
    local error_reader: titan_io.Reader =
      process_diagnostics as system.InputStream
    check(process:is_running(),
          "static captured process exited before receiving stdin")
    writer:write(process_payload .. "\n")
    writer:close()
    check(reader:read_until("\n", true) == process_payload and
          not reader:read() and not error_reader:read(),
          "static process stream Interface dispatch changed payload")
    local streamed_status = process:wait()
    check(streamed_status.code == 0 and not streamed_status.signal and
          streamed_status.signal_number == 0,
          "static process stream Interface changed exit status")
    check(not process:is_running(),
          "static process remained running after wait")
    fs.unlink(marker)
  end
  return 0
end
TITAN

    cppflags=$bundled_cppflags
    ldflags=$bundled_ldflags

    if [[ $OPENSSL_MODE == system ]]; then
        system_openssl_flags
        cppflags="${cppflags:+$cppflags }$system_openssl_cppflags"
        ldflags="${ldflags:+$ldflags }$system_openssl_ldflags"
    fi

    (
        cd "$mode_dir"
        env -u LUA_PATH -u LUA_CPATH -u LUA_PATH_5_5 -u LUA_CPATH_5_5 \
            TITAN_ROCKS_ROOT="$PREFIX" \
            TITAN_PATH_0_6="$LIBRARY_ROOT" TITAN_PATH= \
            TITAN_RUNTIME_PREBUILT=1 \
            TITAN_EXTRA_CPPFLAGS="$cppflags" \
            TITAN_EXTRA_CFLAGS="-fno-strict-aliasing" \
            TITAN_EXTRA_LDFLAGS="$ldflags" \
            "$TITANC" --static static_uv_smoke
    )
    test -x "$executable"

    mv "$PROVIDER" "$PROVIDER_HIDDEN"
    mv "$SHIM_ROOT/titan" "$SHIMS_HIDDEN"
    printf '' | env \
        LUA_PATH="$mode_dir/no-lua/?.lua" \
        LUA_CPATH="$mode_dir/no-lua/?.so" \
        LUA_PATH_5_5="$mode_dir/no-lua/?.lua" \
        LUA_CPATH_5_5="$mode_dir/no-lua/?.so" \
        "$executable" "$marker" "$TITAN_PROCESS_SMOKE_CHILD"
    restore_hidden_provider
    test ! -e "$marker"

    require_no_titan_dependency "$executable"
    require_no_lpeglabel_dependency "$executable"
    require_no_sqlite3_dependency "$executable"
    if [[ $OPENSSL_MODE == bundled ]]; then
        if has_openssl_dependency "$executable"; then
            echo "bundled static Titan executable depends on an OpenSSL DSO" >&2
            exit 1
        fi
    elif ! has_openssl_dependency "$executable"; then
        echo "system OpenSSL static Titan executable has no OpenSSL dependency" >&2
        exit 1
    fi
    if has_libuv_dependency "$executable"; then
        echo "static Titan executable depends on a libuv DSO" >&2
        exit 1
    fi
    if ! defines_uv_version "$executable"; then
        echo "static Titan executable did not absorb reachable libuv objects" >&2
        exit 1
    fi
}

check_openssl_policy() {
    if [[ $OPENSSL_MODE == bundled ]]; then
        if has_openssl_dependency "$PROVIDER"; then
            echo "bundled titan.so unexpectedly depends on an OpenSSL DSO" >&2
            exit 1
        fi
        if ! defines_ssl_do_handshake "$STATIC_ARCHIVE"; then
            echo "bundled titan.a omitted carried OpenSSL definitions" >&2
            exit 1
        fi
    else
        if ! has_openssl_dependency "$PROVIDER"; then
            echo "system OpenSSL titan.so has no OpenSSL dependency" >&2
            exit 1
        fi
        if defines_ssl_do_handshake "$STATIC_ARCHIVE"; then
            echo "system OpenSSL was copied into installed titan.a" >&2
            exit 1
        fi
    fi
}

check_dependency_mode() {
    check_canonical_container
    compare_archive_and_dso_metadata
    if has_public_lpeglabel_symbol "$PROVIDER"; then
        echo "bundled titan.so exports a private LPegLabel symbol" >&2
        exit 1
    fi
    if has_unprefixed_lpeglabel_definition "$STATIC_ARCHIVE"; then
        echo "bundled titan.a contains an unprefixed LPegLabel definition" >&2
        exit 1
    fi
    require_no_lpeglabel_dependency "$PROVIDER"
    require_no_sqlite3_dependency "$PROVIDER"
    check_openssl_policy
    if has_libuv_dependency "$PROVIDER"; then
        echo "bundled titan.so unexpectedly has a dynamic libuv dependency" >&2
        exit 1
    fi
    defines_uv_version "$PROVIDER"
    defines_uv_version "$STATIC_ARCHIVE"
    build_process_child "$OPENSSL_MODE"
    run_mode_smoke "$OPENSSL_MODE"
    build_and_run_static_titan "$OPENSSL_MODE"
}

# Scope selects only OpenSSL. The libuv payload remains bundled in both forms.
case "$scope" in
    bundled|system)
        OPENSSL_MODE=$scope
        check_dependency_mode
        ;;
    both)
        OPENSSL_MODE=bundled
        check_dependency_mode
        # The paired publisher replaces both native forms and all generated
        # shims. The earlier bundled smoke consumes that generation first.
        OPENSSL_MODE=system "$PREFIX/bin/luarocks" make --force
        OPENSSL_MODE=system
        check_dependency_mode
        ;;
esac
