local source_selection = require "titan-compiler.source_selection"
-- Deterministic module C environments and their resolver-owned physical tree.
-- Keep this usable by the checker, C driver and coder without importing any
-- of them: direct checker clients need the same lifecycle as source loaders.
local sha256 = require "titan-compiler.sha256"
local staticmetadata = require "titan-compiler.staticmetadata"
local platform = require "titan-compiler.platform"
local relocation = require "titan-compiler.relocation"

local ffiheaders = {}
ffiheaders.MARKER = "/* Generated by Titan: module C declaration environment. */"

local function descriptor_digest(owner, logical_name, identity, contents, dependencies)
    local parts = { "titan-module-ffi-v2" }
    local function add(value) parts[#parts + 1] = #value .. ":" .. value end
    add(logical_name)
    add(identity)
    add(relocation.includes(owner, contents))
    for _, dependency in ipairs(dependencies) do
        add(dependency.logical_name)
        add(dependency.digest)
    end
    return sha256.hex(table.concat(parts))
end

function ffiheaders.quote_header(name)
    if name:find('["\r\n%z]') then
        return nil, "quoted C header name contains a quote, newline, or NUL byte"
    end
    -- A preprocessor header-name token does not interpret C string escapes.
    -- Extended Windows namespaces require literal backslashes too.
    if platform.windows and name:sub(1, 4) ~= "\\\\?\\" then
        name = name:gsub("\\", "/")
    end
    return '"' .. name .. '"'
end

local function quote_header(name)
    return assert(ffiheaders.quote_header(name))
end

function ffiheaders.relative(from, to)
    local parent = from:match("^(.*)/[^/]+$") or ""
    local from_parts, to_parts = {}, {}
    for part in parent:gmatch("[^/]+") do from_parts[#from_parts + 1] = part end
    for part in to:gmatch("[^/]+") do to_parts[#to_parts + 1] = part end
    local common = 0
    while from_parts[common + 1] and
          from_parts[common + 1] == to_parts[common + 1] do
        common = common + 1
    end
    local result = {}
    for _ = common + 1, #from_parts do result[#result + 1] = ".." end
    for index = common + 1, #to_parts do result[#result + 1] = to_parts[index] end
    return table.concat(result, "/")
end

-- Canonical spelling of the emission policy that produced a header recipe.
-- It is an input of that recipe's digest only: the producer interface digest
-- keeps hashing the rendered helper text, and a producer's own policy is
-- validated by its recorded configuration/codegen certificate.
function ffiheaders.policy_signature(policy)
    if not policy then return "unrecorded" end
    return (policy.line_directives and "line=1" or "line=0") .. ";"
        .. (policy.coverage and "coverage=1" or "coverage=0")
end

-- Canonical identity of one foreign-header recipe: its rendered text, the
-- source-header module list and the policy that produced it. Header paths are
-- deliberately excluded; they are environment, not content.
function ffiheaders.foreign_recipe_digest(recipe)
    if not recipe then return nil end
    local source_headers = recipe.source_headers or {}
    return sha256.hex(table.concat({
        "titan-foreign-header-recipe-v1",
        ffiheaders.policy_signature(recipe.policy),
        tostring(#recipe.prefix), recipe.prefix,
        tostring(#recipe.body), recipe.body,
        tostring(#source_headers), table.concat(source_headers, "\0"),
    }, "\0"))
end

function ffiheaders.foreign_contents(recipe, ffi_header, source_header)
    local includes = { "#include " .. quote_header(ffi_header) }
    for _, modname in ipairs(recipe.source_headers) do
        includes[#includes + 1] = "#include " .. quote_header(source_header(modname))
    end
    return recipe.prefix .. "\n" .. table.concat(includes, "\n") .. "\n" .. recipe.body
end

local function render_includes(modname, includes, typedefs)
    assert(staticmetadata.valid_module_name(modname))
    -- Case and punctuation are significant in a logical module identity.
    local guard = "TITAN_GENERATED_FFI_" .. sha256.hex(modname):upper() .. "_H"
    return table.concat({ ffiheaders.MARKER, "#ifndef " .. guard,
        "#define " .. guard, "", table.concat(includes, "\n"), "",
        table.concat(typedefs or {}, "\n"), "",
        "#endif /* " .. guard .. " */", "" }, "\n")
end

function ffiheaders.render(modname, ast, source_header)
    local includes = {}
    for _, node in ipairs(ast) do
        if not node._ignore and node._tag == "Ast.TopLevelImport"
           and node._source_import then
            local header = source_header and source_header(node) or node._ffi_header
            includes[#includes + 1] = "#include " .. quote_header(assert(header,
                "source import has no generated FFI header"))
        end
    end
    -- Every written directive matters. Actual C guards and macro state decide
    -- what duplicates and diamonds mean, not a spelling-based deduplication.
    for _, node in ipairs(ast) do
        if not node._ignore and node._tag == "Ast.TopLevelForeignImport" then
            includes[#includes + 1] = "#include " .. assert(
                node._include and node._include.rendered,
                "foreign include has no normalized spelling")
        end
    end
    return render_includes(modname, includes, ast._foreign_typedefs)
end

-- The immutable plan retains includes and dependency-ordered raw C typedefs.
-- It can be restored without an AST or a source-foreign function companion.
function ffiheaders.plan_contents(modname, logical_name, dependencies, direct_includes, typedefs)
    local includes = {}
    for _, dependency in ipairs(dependencies) do
        includes[#includes + 1] = "#include " .. quote_header(
            ffiheaders.relative(logical_name, dependency.logical_name))
    end
    for _, include in ipairs(direct_includes) do
        assert(type(include) == "string" and not include:find("[\r\n%z]"),
            "invalid generated FFI include")
        assert(include:match('^".*"$') or include:match("^<[^<>]+>$"),
            "invalid generated FFI include")
        includes[#includes + 1] = "#include " .. include
    end
    for _, declaration in ipairs(typedefs or {}) do
        assert(type(declaration) == "string"
            and not declaration:find("[\r\n%z]")
            and declaration:match("^typedef .+;$"),
            "invalid generated FFI typedef declaration")
    end
    return render_includes(modname, includes, typedefs)
end

function ffiheaders.validate_plan(descriptor)
    assert(staticmetadata.valid_module_name(descriptor.modname),
        "invalid generated FFI module name")
    assert(descriptor.logical_name == descriptor.modname:gsub("[.]", "/") .. ".ffi.h",
        "invalid generated FFI logical name")
    local roots = { relocation_roots = descriptor.roots or {} }
    assert(type(descriptor.identity) == "string"
        and platform.is_absolute(relocation.resolve(roots, descriptor.identity))
        and not descriptor.identity:find("[\r\n%z]"), "invalid generated FFI identity")
    local contents = ffiheaders.plan_contents(descriptor.modname,
        descriptor.logical_name, descriptor.dependencies, descriptor.direct_includes,
        descriptor.typedef_declarations)
    assert(contents == descriptor.contents, "generated FFI contents disagree with its declaration plan")
    assert(descriptor.digest == descriptor_digest(roots, descriptor.logical_name,
        descriptor.identity, contents, descriptor.dependencies),
        "generated FFI digest disagrees with its declaration plan")
    return true
end

function ffiheaders.remember_file(owner, filename)
    owner.source_foreign_header_temporaries =
        owner.source_foreign_header_temporaries or {}
    owner.source_foreign_header_paths = owner.source_foreign_header_paths or {}
    if owner.source_foreign_header_paths[filename] then return end
    owner.source_foreign_header_paths[filename] = true
    local paths = owner.source_foreign_header_temporaries
    paths[#paths + 1] = filename
end

local function ensure_bundle(owner)
    if owner.source_ffi_header_bundle then return owner.source_ffi_header_bundle end
    local root, err = owner.io:tmpname()
    if not root then return nil, err end
    -- Register the owned reservation before a strategy can suspend, and
    -- transfer ownership to the directory before the mkdir operation.
    ffiheaders.remember_file(owner, root)
    local removed, remove_err = owner.io:unlink(root, true)
    if not removed then return nil, remove_err end
    table.remove(owner.source_foreign_header_temporaries)
    owner.source_foreign_header_paths[root] = nil
    owner.source_ffi_header_directories = owner.source_ffi_header_directories or {}
    local directories = owner.source_ffi_header_directories
    directories[#directories + 1] = root
    local created, create_err = owner.io:mkdir(root, true)
    if not created then return nil, create_err end
    owner.source_ffi_header_bundle = root
    return root
end

function ffiheaders.filename(owner, logical_name)
    local root, err = ensure_bundle(owner)
    if not root then return nil, err end
    local relative_parent = logical_name:match("^(.*)/[^/]+$")
    local directory = root
    for component in (relative_parent or ""):gmatch("[^/]+") do
        directory = directory .. "/" .. component
        local existing, stat_err = owner.io:lstat(directory)
        if stat_err then return nil, stat_err end
        if not existing then
            local directories = owner.source_ffi_header_directories
            directories[#directories + 1] = directory
            local created, create_err = owner.io:mkdir(directory, true)
            if not created then return nil, create_err end
        elseif existing.kind ~= "directory" then
            return nil, "checking-header parent is not a directory: " .. directory
        end
    end
    return root .. "/" .. logical_name, nil, root
end

local function origin_identity(owner, modname, native_output)
    local path = source_selection.output_stem(native_output, modname) .. ".ffi.h"
    if platform.windows then
        -- This is a normalized logical origin, not a physical header-input key.
        -- Preserve the existing Unix identity algorithm below.
        if not platform.is_absolute(path) then
            local cwd, err = owner.io:cwd()
            if not cwd then return nil, err end
            path, err = platform.absolute(path, cwd, owner.io)
            if not path then return nil, err end
        end
        return relocation.path(owner, platform.path.normalize(path))
    end
    if path:sub(1, 1) ~= "/" then
        local cwd, err = owner.io:cwd()
        if not cwd then return nil, err end
        path = cwd .. "/" .. path
    end
    local components = {}
    for component in path:gmatch("[^/]+") do
        if component == ".." then
            if #components > 0 then table.remove(components) end
        elseif component ~= "." then
            components[#components + 1] = component
        end
    end
    return relocation.path(owner, "/" .. table.concat(components, "/"))
end

local function materialize_descriptor(owner, descriptor, retained)
    retained = retained or {}
    if retained[descriptor] then return retained[descriptor] end
    if descriptor.bundle_root == owner.source_ffi_header_bundle
       and descriptor.bundle_root ~= nil
       and descriptor.filename == descriptor.bundle_root .. "/" .. descriptor.logical_name then
        retained[descriptor] = descriptor
        return descriptor
    end
    local dependencies = {}
    for _, dependency in ipairs(descriptor.dependencies) do
        local current, err = materialize_descriptor(owner, dependency, retained)
        if not current then return nil, err end
        dependencies[#dependencies + 1] = current
    end
    local filename, err, bundle_root = ffiheaders.filename(owner, descriptor.logical_name)
    if not filename then return nil, err end
    local current = {
        modname = descriptor.modname,
        logical_name = descriptor.logical_name,
        filename = filename,
        bundle_root = bundle_root,
        identity = descriptor.identity,
        contents = descriptor.contents,
        direct_includes = descriptor.direct_includes,
        typedef_declarations = descriptor.typedef_declarations,
        dependencies = dependencies,
        search_inputs = descriptor.search_inputs,
        roots = descriptor.roots,
        digest = descriptor.digest,
    }
    ffiheaders.remember_file(owner, filename)
    local wrote, write_err = owner.io:write_file(filename, descriptor.contents)
    if not wrote then return nil, write_err end
    retained[descriptor] = current
    return current
end

function ffiheaders.materialize(owner, descriptor)
    -- Descriptors are immutable compiler-owned plans. Their content digest is
    -- computed when prepared and retained by the compiler's graph codec.
    return materialize_descriptor(owner, descriptor)
end

function ffiheaders.prepare(owner, modname, ast, sourcef)
    assert(staticmetadata.valid_module_name(modname))
    local logical_name = modname:gsub("[.]", "/") .. ".ffi.h"
    local identity, identity_err = origin_identity(owner, modname, sourcef)
    if not identity then return nil, identity_err end
    local dependencies = {}
    local contents = ffiheaders.render(modname, ast, function(node)
        local dependency = assert(node._ffi_header_descriptor,
            "source import has no checking FFI descriptor")
        dependencies[#dependencies + 1] = dependency
        return ffiheaders.relative(logical_name, dependency.logical_name)
    end)
    -- The normalized authored include retains its original lookup candidates.
    -- Preserve these runtime observations without changing raw probe identity
    -- when the chosen header and generated environment are unchanged.
    local search_inputs, direct_includes = {}, {}
    for _, node in ipairs(ast) do
        if not node._ignore and node._tag == "Ast.TopLevelForeignImport" then
            direct_includes[#direct_includes + 1] = node._include.rendered
            for _, input in ipairs(node._include.c_header_search_inputs or {}) do
                search_inputs[#search_inputs + 1] = input
            end
        end
    end
    local typedefs = {}
    for _, declaration in ipairs(ast._foreign_typedefs or {}) do
        typedefs[#typedefs + 1] = declaration
    end
    local descriptor = {
        modname = modname,
        logical_name = logical_name,
        identity = identity,
        contents = contents,
        direct_includes = direct_includes,
        typedef_declarations = typedefs,
        dependencies = dependencies,
        search_inputs = search_inputs,
        roots = owner.relocation_roots,
        digest = descriptor_digest(owner, logical_name, identity, contents, dependencies),
    }
    -- Direct checker clients may borrow plans from independent/closed loaders;
    -- stage those actual generated files under this owner's root.
    local current, materialize_err = ffiheaders.materialize(owner, descriptor)
    if not current then return nil, materialize_err end
    local dependency_index = 0
    for _, node in ipairs(ast) do
        if not node._ignore and node._tag == "Ast.TopLevelImport"
           and node._source_import then
            dependency_index = dependency_index + 1
            local dependency = current.dependencies[dependency_index]
            node._ffi_header_descriptor = dependency
            node._ffi_header = dependency.filename
        end
    end
    ast._ffi_header = current
    return current
end

function ffiheaders.close(owner)
    local first_error
    local remaining_headers, remaining_paths = {}, {}
    for _, filename in ipairs(owner.source_foreign_header_temporaries or {}) do
        local attributes, attribute_err = owner.io:lstat(filename)
        if attributes then
            local removed, remove_err = owner.io:unlink(filename)
            if not removed then
                first_error = first_error or remove_err or
                    ("could not remove temporary source foreign header '" .. filename .. "'")
                remaining_headers[#remaining_headers + 1] = filename
                remaining_paths[filename] = true
            end
        elseif attribute_err then
            first_error = first_error or attribute_err
            remaining_headers[#remaining_headers + 1] = filename
            remaining_paths[filename] = true
        end
    end
    owner.source_foreign_header_temporaries =
        #remaining_headers > 0 and remaining_headers or nil
    owner.source_foreign_header_paths =
        #remaining_headers > 0 and remaining_paths or nil
    local remaining_directories = {}
    local directories = owner.source_ffi_header_directories or {}
    for index = #directories, 1, -1 do
        local directory = directories[index]
        local attributes, attribute_err = owner.io:lstat(directory)
        if attributes then
            local removed, remove_err = owner.io:rmdir(directory)
            if not removed then
                -- Another cleanup may remove the directory while the async
                -- lstat result is being delivered. Confirm that retirement
                -- completed before retaining a failed removal for retry.
                local current, inspection_err = owner.io:lstat(directory)
                if current ~= nil or inspection_err ~= nil then
                    first_error = first_error or remove_err or
                        ("could not remove checking-header directory '" .. directory .. "'")
                    table.insert(remaining_directories, 1, directory)
                end
            end
        elseif attribute_err then
            first_error = first_error or attribute_err
            table.insert(remaining_directories, 1, directory)
        end
    end
    owner.source_ffi_header_directories =
        #remaining_directories > 0 and remaining_directories or nil
    if #remaining_headers == 0 and #remaining_directories == 0 then
        owner.source_ffi_header_bundle = nil
    end
    if first_error then return nil, first_error end
    return true
end

return ffiheaders
